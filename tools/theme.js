// Тема сайта. Один файл на все страницы — и один выключатель в нём.
//
// Светлая тема выключена. Не удалена: палитра, ручной выбор, его протухание
// через четыре часа и слежение за системой — всё на месте и работает. Погашена
// только сама возможность выбрать, и возвращается она одним true вот здесь.
//
// Почему выключена. Схема сервера нарисована как освещённый предмет в тёмной
// комнате: самая частая её краска светло-серая — это блики, гравировка и
// кромки, а не корпус, и таких заливок треть от всех. В светлой теме им не на
// чем светиться, и машина становится либо пятном на бумаге, либо туманом. Это
// не перекраска, а второй рисунок, и до него ещё не дошли руки.
//
// Почему отдельным файлом, а не строкой в каждой странице. Страниц на сайте
// три, и флаг стоял в двух из них порознь: включить светлую тему значило
// вспомнить про все и не забыть ни одной, а забытая страница — это не «света
// нет», это разъехавшийся сайт. Теперь правится одно место.
//
// Грузится синхронно в <head>, до первой отрисовки: иначе на долю секунды
// мелькнёт не та тема.
var THEME_CHOICE = false;

// Пустое хранилище означает «следуй за системой», поэтому пишем туда только
// то, что пользователь выбрал руками. Живёт этот выбор недолго и уступает
// системе: рядом с ним лежит отметка, когда его сделали и какая тема была
// тогда у системы. Если система с тех пор передумала — скажем, наступила ночь
// и она ушла в тёмную — или если выбор просто отлежал свои часы, он
// снимается, и страница снова идёт за системой.
(function () {
    var LIFE = 4 * 60 * 60 * 1000;
    var system = window.matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
    var saved = null;
    try {
        if (+localStorage.getItem('theme-at') > Date.now() - LIFE
            && localStorage.getItem('theme-sys') === system) {
            saved = localStorage.getItem('theme');
        } else {
            localStorage.removeItem('theme');
            localStorage.removeItem('theme-at');
            localStorage.removeItem('theme-sys');
        }
    } catch (e) {}
    if (saved !== 'light' && saved !== 'dark') saved = null;
    // Ветка с THEME_CHOICE — единственное место, где выключение вообще
    // сказывается. Атрибут при этом ставится всегда, и этого довольно, чтобы
    // светлые правила не сработали: `:root[data-theme="light"]` не совпадёт, а
    // системное правило написано на `:root:not([data-theme])` — то есть на
    // «атрибута нет вовсе».
    document.documentElement.setAttribute('data-theme',
        THEME_CHOICE ? (saved || system) : 'dark');
    if (!THEME_CHOICE) document.documentElement.classList.add('theme-locked');
})();
