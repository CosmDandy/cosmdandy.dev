"""райзеры: тонкий уголок, широкой частью к задней стенке.

Кронштейн действительно тонкий: пара миллиметров стали. Широкая часть у
задней панели, ножка уходит вперёд, к центру машины.
Углы штампованной скобы: наружные грани режут прямо по контуру заготовки,
а внутренний угол всегда скруглён — на прямом угле сталь трескается.

Райзеров два, и они разные не только размером. В верхнем стоит сетевая
карта, её торец — гнёзда SFP+. Нижний в этой сборке пуст, и пуст честно:
плата райзера со слотом на месте, карты нет, а окно в задней стенке закрыто
глухой планкой. Раньше в него рисовали такую же карту, как в верхний, — и
схема расходилась с паспортом, где второй слот значится свободным.
"""

# Свой прямоугольник: сборка проверит, что узел из него не вышел.
# Первая карта доходит до задней стенки: её торец — это гнёзда SFP+.
BOUNDS = (992, 150, 316, 340)

from board.geom import BRACKET_W, RISER, X_IO, X_REAR, riser_seat
from board.ink import mono, silk_boxed
from board.lamps import act_led, fault_at, lamp
from board.metal import finned_sink, hexgrid
from board.palette import COLD, STEEL
from board.ports import qsfp, sfp, turned
from board.revision import stamp
from board.spec import PORTS


def render(cv):
    T, RI = BRACKET_W, 18   # ширина стойки и радиус внутреннего угла
    x0 = X_REAR + 12
    # Стойка кронштейна встаёт в проём перфорированного листа: её левая грань
    # совпадает с левым краем листа, дальше вглубь машины лист продолжается
    # своей перфорацией. Поэтому правый край считается от кромки листа плюс
    # ширина стойки, а не от текстолита и не от панели: кронштейн — часть
    # задней стенки, а не то, что стоит перед ней.
    x1 = X_IO - 24 + T
    cw = x1 - x0 - T - 46

    # Подпись ведёт к торцу карты, а не к стенке: гнёзда принадлежат ей.
    # Бирки правой кромки разведены на равные промежутки: 160, 330, 500, 670.
    # Прежние 218, 436, 596, 676 давали 218, 160 и 80 — три ссылки жались к
    # нижней трети, и весь вес схемы уезжал в правый нижний угол, при том что
    # верхняя половина кромки пустовала.
    #
    # Верхняя заходит на блок питания, и это нарочно: бирка лежит поверх всего
    # и читается на любом фоне, а место над картой иначе не занять ничем.
    cv.callouts.append((X_IO - 30, 160, X_IO - 8, 226, "LinkedIn", "end",
                        "https://linkedin.com/in/cosmdandy", "ocp",
                        "профиль", "linkedin"))
    # Телеграм переехал сюда с гигабитного гнезда: канал теперь висит на
    # стогигабитной карте. Бирка стоит на прежнем месте правой кромки — шаг
    # между бирками важнее, чем то, к какому железу тянется выноска.
    cv.callouts.append((X_IO - 30, 385, X_IO - 8, 367, "Telegram", "end",
                        "/tg/", "cx", "канал", "telegram"))

    for k, ((y, hh), up) in enumerate(zip(RISER, (True, False))):
        # Кронштейн со своей платой занимает карман целиком — то же молчание,
        # что было у памяти и у гнёзд процессоров: узел нарисован, а регистр
        # про него не знает и считает место свободным.
        cv.busy(x0, y, x1 - x0, hh, pad=0)
        if up:
            # полка сверху, стойка справа: вогнутый угол один — (x1-T, y+T)
            d = (f'M{x0} {y} H{x1} V{y+hh} H{x1-T} V{y+T+RI} '
                 f'A{RI} {RI} 0 0 0 {x1-T-RI} {y+T} H{x0} Z')
            hex_y, hex_h = y + T + 6, hh - T - 12
            edge_y = y + T + 6           # краевой разъём платы райзера
        else:
            d = (f'M{x0} {y+hh} H{x1} V{y} H{x1-T} V{y+hh-T-RI} '
                 f'A{RI} {RI} 0 0 1 {x1-T-RI} {y+hh-T} H{x0} Z')
            hex_y, hex_h = y + 4, hh - T - 8
            edge_y = y + hh - T - 6


        # Райзер — это две вещи: стальной кронштейн, за который тянут, и его
        # собственная плата со слотом. Плату видно вдоль кронштейна: карта
        # втыкается именно в неё, а сталь только держит.
        riser_pcb = (
            f'<rect x="{x0+12}" y="{edge_y-14}" width="{cw+16}" height="30" rx="2" '
            f'fill="#123642" stroke="rgba(42,161,152,0.34)"/>'
            # краевой разъём самой платы райзера — им она и садится в системную
            + ''.join(f'<line x1="{x0+20+j*7}" y1="{edge_y+9}" x2="{x0+20+j*7}" y2="{edge_y+14}" '
                      f'stroke="rgba(184,150,51,0.5)" stroke-width="1.6"/>'
                      for j in range(int(cw // 7)))
            + f'<rect x="{x0+18}" y="{edge_y-10}" width="{cw}" height="9" rx="1" fill="#05090b" '
              f'stroke="rgba(147,161,161,0.30)"/>'
            + ''.join(f'<line x1="{x0+24+j*9}" y1="{edge_y-9}" x2="{x0+24+j*9}" y2="{edge_y-2}" '
                      f'stroke="rgba(133,153,0,0.26)"/>' for j in range(int(cw // 9) - 1)))

        if up:
            # Сама карта: плата, крупный пассивный радиатор поверх чипа и клетки
            # портов на дальнем торце — у задней стенки. Вынимаешь райзер —
            # карта с портами уезжает вместе с ним. Карта тянется до самой
            # стенки: её торец и есть гнёзда, которые видно снаружи.
            card_y = edge_y - 46
            card_w = X_IO - x0 - 18
            # Радиатор занимает большую часть платы — так он и стоит на живой
            # карте: под ним контроллер на десять гигабит, и греется он всерьёз.
            # Рисуется тем же finned_sink, что и силовой в блоке питания:
            # рёбра вдоль потока, винты по углам. Прежний был вчетверо мельче и
            # читался просто заштрихованным прямоугольником.
            sink_x = x0 + 40
            sink_w = X_IO - 10 - sink_x
            card = (riser_pcb
                    + f'<rect x="{x0+18}" y="{card_y}" width="{card_w}" height="56" rx="1" '
                      f'fill="#0f1c24" stroke="rgba(42,161,152,0.34)"/>'
                    + finned_sink(sink_x, card_y + 4, sink_w, 38, r=4.4, inset=8)
                    + silk_boxed(x0 + 70, card_y + 50, "PCIE_X8_GF1 REV 1.01", 5))
            # Гнёзда на торце карты. Раньше они были нарисованы прямо на стенке
            # и ни к чему не вели: дырки в корпусе. Теперь видно, что это торец
            # карты, и вместе с райзером они уезжают наружу.
            #
            # Ламп у порта две, и обе о разном. LNK — состояние: держится, пока
            # линк поднят, и цветом говорит, на какой скорости он поднялся.
            # Зелёный — свои десять гигабит, янтарный — линк упал до гигабита,
            # то есть карта работает, но не так, как заявлена. ACT — событие:
            # мигает на трафике. Раньше на две розетки приходилось три лампы
            # без подписей, и какая из них про что, сказать было нельзя.
            def sfp_leds(p, cx, degraded):
                lnk_color = "#b58900" if degraded else "#859900"
                ly = card_y + 56
                return (lamp('led-link', cx - 7, ly, 2.2, lnk_color)
                        + mono(cx - 7, ly + 9, "LNK", 3.6, op=0.32)
                        + act_led(3 + p, cx + 7, ly, 2.2, "#859900", salt=2 + p)
                        + mono(cx + 7, ly + 9, "ACT", 3.6, op=0.32))

            ports = [(f'<rect x="{X_IO}" y="{card_y-4}" width="86" height="76" rx="4" '
                      f'fill="#13282c" stroke="rgba(42,161,152,0.50)"/>')]
            # Оба порта в норме. Второй был жёстко помечен упавшим до гигабита —
            # и это спорило с самой машиной: /sys/class/net показывал оба
            # поднятыми, lspci рапортовал две десятки. Схема рисует исправную
            # машину, а упавший линк — это состояние, которое приходит извне, а
            # не свойство платы. Янтарный цвет лампы при этом остался: он
            # включается, когда линк действительно падает.
            # Клетки развёрнуты на четверть оборота: гнездо смотрит НАРУЖУ,
            # в стенку, а не на зрителя. Модуль входит снаружи внутрь машины,
            # и с этого вида должен быть виден его ход, а не морда разъёма —
            # мордой к смотрящему клетка не стоит никогда.
            #
            # Развёрнутая клетка вдвое выше, чем была широка, и стопкой две
            # уже не встают: они переехали в ряд, бок о бок, как на живой
            # двухпортовой планке. Лампы вслед за ними — под каждой своя пара.
            for p in range(2):
                cx = X_IO + 25 + p * 36
                cy = card_y + 24
                ports.append(turned(sfp(cx - 24, cy - 11, w=48, h=22), cx, cy))
                ports.append(sfp_leds(p, cx, False))
            # Подписи о том, что это за карта, здесь больше нет. Она входила в
            # ту же группу, что и сама карта, и уезжала вместе с ней: вынимаешь
            # райзер — надпись едет вверх и повисает над платой, объясняя
            # пустое место. Что стоит в слоте, и так сказано на самом слоте
            # (RISER_1 · PCIE_G5 ×16) и в паспорте машины.
            ports = ''.join(ports)
            card += (f'<g class="unit" data-unit="ocp" data-group="ocp" '
                     f'data-href="https://linkedin.com/in/cosmdandy">{ports}</g>')
        else:
            # Вторая карта — стогигабитная, и она низкопрофильная: на этот
            # райзер приходится 80 единиц против 176 у верхнего, и такая карта
            # в живой машине именно half-height. Радиатор у неё во всю плату:
            # контроллер на сотню греется сильнее десятигигабитного, и на
            # живой карте под ним стоит глухой блок с рёбрами, а не пластинка.
            card_y = edge_y - 40
            card_w = X_IO - x0 - 18
            sink_x = x0 + 40
            sink_w = X_IO - 10 - sink_x
            card = (riser_pcb
                    + f'<rect x="{x0+18}" y="{card_y}" width="{card_w}" height="46" rx="1" '
                      f'fill="#0f1c24" stroke="rgba(42,161,152,0.34)"/>'
                    + finned_sink(sink_x, card_y + 4, sink_w, 30, r=4.4, inset=8)
                    + silk_boxed(x0 + 70, card_y + 41, "PCIE_X16_GF2 REV 1.00", 5))

            # Гнёзда QSFP28. Их два, как и на верхней карте, но клетка шире и
            # выше: под сотню идут четыре линии вместо одной. Ламп у порта
            # тоже две и о том же — состояние линка и трафик.
            def qsfp_leds(p, cx):
                ly = card_y + 50
                return (lamp('led-link', cx - 8, ly, 2.2, "#859900")
                        + mono(cx - 8, ly + 9, "LNK", 3.6, op=0.32)
                        + act_led(7 + p, cx + 8, ly, 2.2, "#859900", salt=6 + p)
                        + mono(cx + 8, ly + 9, "ACT", 3.6, op=0.32))

            ports = [(f'<rect x="{X_IO}" y="{card_y-14}" width="86" height="78" rx="4" '
                      f'fill="#13282c" stroke="rgba(42,161,152,0.50)"/>')]
            # Развёрнуты так же, как на верхней карте: вход смотрит наружу.
            # Клетка тут шире и длиннее, и в ряд две встают впритык — на живой
            # низкопрофильной карте ровно так и есть, планка занята ими целиком.
            for p in range(2):
                cx = X_IO + 24 + p * 38
                cy = card_y + 14
                ports.append(turned(qsfp(cx - 32, cy - 15, w=64, h=30), cx, cy))
                ports.append(qsfp_leds(p, cx))
            ports = ''.join(ports)
            card += (f'<g class="unit" data-unit="cx" data-group="cx" '
                     f'data-href="/tg/">{ports}</g>')

        # Лепесток-ручка на внешнем торце: райзер вынимают вверх, взявшись за
        # него. Голубой, а не терракотовый: райзер меняют только на
        # обесточенной машине, и цвет ручки — это и есть предупреждение.
        ty = y + (-10 if up else hh - 6)
        py = y + (6 if up else hh - T + 6)
        tab = (
            # Торцевая ручка стоит на полке кронштейна, левее окна под планку
            # карты. Прежние координаты клали её на четырнадцать единиц прямо
            # на торец карты: ручка кронштейна поверх чужих гнёзд — то, чего на
            # машине не бывает, за ручку как раз и тянут, чтобы карту не
            # трогать.
            f'<rect x="{X_IO-46}" y="{ty}" width="{T-24}" height="16" rx="2" fill="{COLD}" '
            f'stroke="rgba(238,232,213,0.55)" stroke-width="1.2"/>'
            f'<rect x="{X_IO-40}" y="{ty+4}" width="{T-36}" height="8" rx="1" fill="rgba(238,232,213,0.22)"/>'
            # на полке, ближе к центру машины: за него райзер и качают
            f'<rect x="{x0-8}" y="{py}" width="16" height="{T-12}" rx="2" fill="{COLD}" '
            f'stroke="rgba(238,232,213,0.55)" stroke-width="1.2"/>'
            f'<rect x="{x0-4}" y="{py+5}" width="8" height="{T-22}" rx="1" fill="rgba(238,232,213,0.22)"/>')

        # Ответный слот на плате — под краевыми контактами карты. Он остаётся,
        # когда райзер вынимают: разъём распаян, а кронштейн съёмный.
        # Слот длиннее карты и тянется вправо, к задней стенке: у PCIe ×16
        # разъём заметно длиннее краевых контактов карты ×8, и на плате это
        # первое, по чему слот узнают. Правый край держим у стойки
        # кронштейна — дальше начинается сталь.
        slot_w = (x1 - T - 6) - (x0 + 18)
        cv.add(f'''<g class="decor">
      <rect x="{x0+14}" y="{edge_y-3}" width="{slot_w+8}" height="14" rx="2" fill="#101a22"
            stroke="rgba(147,161,161,0.34)"/>
      <rect x="{x0+18}" y="{edge_y+1}" width="{slot_w}" height="6" rx="1" fill="#060d10"/>
      {''.join(f'<line x1="{x0+22+j*9}" y1="{edge_y+1}" x2="{x0+22+j*9}" y2="{edge_y+7}" stroke="rgba(133,153,0,0.22)"/>' for j in range(int(slot_w // 9) - 1))}
      {silk_boxed(x0 + 18 + slot_w / 2, edge_y + 22, f"RISER_{k+1} · PCIE_G5 ×16", 6)}
    </g>''')
        # Соты кронштейна — тем же размером и зазором, что на крышке и на
        # борту: на живой машине (см. rear-riser-overview) это одна и та же
        # штамповка, и полем более частой сетки кронштейн читался бы деталью от
        # другой машины. Стоит поле там же, где на фото: поперёк всей ширины
        # кронштейна, в его задней четверти.
        #
        # Дырки настоящие, пробитые маской, а не тёмные шестиугольники поверх
        # стали. Полупрозрачной заливки тут мало по простой причине: под ней
        # остаётся непрозрачный кронштейн, и сквозь такую «дырку» видно его же,
        # только темнее. Плата видна только там, где стали физически нет.
        cv.add(f'''<g class="pick riser" data-riser="{k+1}" style="--seat:{riser_seat(k)}">
      <g class="pick-body">
        <g class="riser-lift">
          <defs><mask id="riser-perf-{k}" maskUnits="userSpaceOnUse">
            <rect x="{x0 - 24}" y="{y - 24}" width="{x1 - x0 + 48}" height="{hh + 48}" fill="#fff"/>
            {hexgrid(x1 - T + 8, hex_y, T - 16, hex_h, s=6, gap=5, fill='#000', stroke='none')}
          </mask></defs>
          <path d="{d}" fill="{STEEL}" stroke="rgba(147,161,161,0.30)" stroke-width="1.4"
                mask="url(#riser-perf-{k})"/>
          <g mask="url(#riser-perf-{k})">{hexgrid(x1 - T + 8, hex_y, T - 16, hex_h,
             s=6, gap=5, fill='none', stroke='rgba(147,161,161,0.26)')}</g>
          {card}
          {tab}
        </g>
      </g>
      {fault_at(cv, x0-14, y + (96 if up else 40), 5)}
      {stamp(x0 + (86 if up else 18), y + hh - 6 if up else y + 12, "райзеры")}
    </g>''')
