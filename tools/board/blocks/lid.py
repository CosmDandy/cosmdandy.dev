"""гравировка на крышке.

Крышка накрывает машину от стенки вентиляторов до задней кромки. Фронт она
не закрывает вовсе: панель управления и корзина дисков выходят из шасси
вперёд, и на живой машине верхний лист до них не доходит.

Подписи — не названия железа, а то, куда ведёт узел: схема сама объясняет,
что где лежит.

Все координаты крышка берёт из geom, теми же именами, что и сами узлы. Пока
она держала свои числа, каждый переезд оставлял её накрывать пустое место —
то шесть отсеков вместо восьми, то райзер там, где его уже нет.

Чего на крышке нет и почему. Вентиляторов: на живой машине стенка стоит под
листом целиком, и рисовать её сверху значило показывать один и тот же узел
дважды — на плате он уже нарисован, с лопастями и лампами. Общей обводки
платы: лист не повторяет контур текстолита, он его перекрывает.
"""

from board.geom import (
    BANK_N,
    DIMM_SOCK_W,
    FAN_W,
    IO_BOARD,
    IO_Y,
    JACK_H,
    JACK_PITCH,
    LID_BTN,
    PITCH,
    PSU_H,
    PSU_W,
    PSU_Y,
    RISER,
    SLOT_H,
    SOCKET_H,
    SOCKET_W,
    X_BP,
    X_CORE,
    X_FAN,
    X_IO,
    X_REAR,
    X_SOCK,
    Y_BANK_C,
    Y_BANK_L,
    Y_BANK_R,
    Y_CPU0,
    Y_CPU1,
    Y_PSU_BOT,
    Y_PSU_TOP,
    H,
    W,
)
from board.metal import hexgrid, rating_label, service_label, service_legend
from board.palette import COLD

# Кромка крышки: всё, что левее, остаётся открытым.
LID_X = X_BP - 2
LID_R = W - 4
# Выемки на задней кромке — под кронштейны райзеров: на фото верхней крышки
# лист в этих местах отступает внутрь, иначе его не завести на место поверх
# уже стоящих кронштейнов.
NOTCH = 16

# Перфорация. Только два поля, и оба — над тем, что дышит через лист: над
# задней стенкой с гнёздами (она лежит ровно между отсеками БП) и над самими
# отсеками. Прежние две продольные полосы шли поперёк всей крышки и не
# приходились ни на что.
PERF = [(X_IO - 8, Y_PSU_TOP + 6, LID_R - NOTCH - 8 - (X_IO - 8),
         Y_PSU_BOT - Y_PSU_TOP - 12)]
# Шильдик питания прижат к правой кромке, и перфорация отсека начинается,
# отступив от него.
PLATE_W, PLATE_H = 164, 46          # сам шильдик, до поворота на 90°
PLATE_CX = LID_R - 8 - PLATE_H / 2
PERF += [(X_REAR + 12, y + 8, PLATE_CX - PLATE_H / 2 - 16 - (X_REAR + 12), PSU_H - 16)
         for y in PSU_Y]


def render(cv):
    def frame(x, y, w, h, rx=0, op=0.28):
        return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="none" '
                f'stroke="rgba(147,161,161,{op})" stroke-width="1.4"/>')

    def label(x, y, t, size=11, anchor_="middle", op=0.42, turn=False):
        spin = f' transform="rotate(-90 {x} {y})"' if turn else ''
        return (f'<text x="{x}" y="{y}"{spin} text-anchor="{anchor_}" fill="rgba(147,161,161,{op})" '
                f'font-family="ui-monospace, Menlo, monospace" font-size="{size}" letter-spacing="0.1em">{t}</text>')

    # Тело крышки: лист от стенки вентиляторов до задней кромки. Фронт открыт
    # целиком — и кнопка питания, и корзина, из которой диск выезжает наружу.
    # Правая кромка идёт с выемками под кронштейны райзеров.
    # Вырезов в задней кромке два, и оба на съёмное: один под кронштейны
    # райзеров, другой под встроенные сетевые карты. Под мелочью — USB и D-Sub —
    # выреза нет: там ничего не снимают, и лист идёт сплошным.
    #
    # Спуски под сорок пять градусов, а не прямым углом: штампованный лист так
    # и режут, прямой угол — это концентратор напряжений, с него лист и рвётся.
    # Отсюда трапеция. Углы, и внешние и внутренние, скруглены: r·tg(22.5°) —
    # это отступ, на который скругление съедает каждую сторону при повороте на
    # сорок пять градусов, а 0.293·r — то же самое, разложенное по осям.
    def notch(y1, y2, d=NOTCH, r=7):
        t, k = 0.414 * r, 0.293 * r
        return (f'V{y1 - t:.1f} a{r} {r} 0 0 0 {-k:.1f} {k:.1f} '
                f'L{LID_R - d + k:.1f} {y1 + d - k:.1f} '
                f'a{r} {r} 0 0 1 {-k:.1f} {k:.1f} '
                f'V{y2 - d - t:.1f} a{r} {r} 0 0 1 {k:.1f} {k:.1f} '
                f'L{LID_R - k:.1f} {y2 - k:.1f} '
                f'a{r} {r} 0 0 0 {k:.1f} {k:.1f} ')

    edge = [f'M{LID_X+4} 4 H{LID_R} ']
    # Один вырез на оба слота райзеров: снимают их вместе, и перемычка между
    # двумя вырезами была бы язычком стали в палец шириной.
    edge.append(notch(RISER[0][0] - 8, RISER[1][0] + RISER[1][1] + 8))
    # Второй — под гнёзда встроенных сетевых карт.
    edge.append(notch(IO_Y - 8, IO_Y + 2 * JACK_PITCH + JACK_H + 8))
    edge.append(f'V{H-8} a4 4 0 0 1 -4 4 H{LID_X+4} a4 4 0 0 1 -4 -4 V8 a4 4 0 0 1 4 -4 Z')
    body = ''.join(edge)

    # Соты — настоящие дырки, а не рисунок на листе. Полупрозрачной заливки,
    # какой они сделаны на борту, здесь мало: под крышкой мигают лампы гнёзд, и
    # владелец просил, чтобы сквозь перфорацию было видно именно их. Поэтому
    # лист пробивается маской, а поверх остаётся только кромка отверстия.
    cv.add('<defs><mask id="lid-perf" maskUnits="userSpaceOnUse">'
           f'<rect x="{LID_X}" y="0" width="{W-LID_X}" height="{H}" fill="#fff"/>'
           + ''.join(hexgrid(*z, s=6, gap=5, fill="#000", stroke="none") for z in PERF)
           + '</mask></defs>')
    cv.add(f'<path d="{body}" fill="#161f24" stroke="rgba(147,161,161,0.30)" '
           f'stroke-width="1.4" mask="url(#lid-perf)"/>')
    cv.add('<g class="decor">'
           + ''.join(hexgrid(*z, s=6, gap=5, fill="none",
                             stroke="rgba(147,161,161,0.26)") for z in PERF)
           + '</g>')

    # память и процессоры — с назначением, а не с маркировкой. Рамка банка
    # обводит ровно сокеты: X_CORE-2 и BANK_N·PITCH — те же числа, которыми
    # память рисует себя саму, иначе крышка обводит воздух вокруг банка.
    bank_h = (BANK_N - 1) * PITCH + SLOT_H + 2
    for y0 in (Y_BANK_L, Y_BANK_C, Y_BANK_R):
        cv.add(frame(X_CORE - 2, y0 - 1, DIMM_SOCK_W, bank_h, 0, 0.26))
        for i in range(BANK_N):
            yy = y0 + i * PITCH + SLOT_H / 2
            cv.add(f'<line x1="{X_CORE+6}" y1="{yy}" x2="{X_CORE + DIMM_SOCK_W - 12}" y2="{yy}" '
                   f'stroke="rgba(147,161,161,0.14)" stroke-width="1.2"/>')
    cv.add(label(X_CORE + DIMM_SOCK_W / 2, Y_BANK_C + bank_h / 2 + 5, "Blog", 15))

    for y in (Y_CPU0, Y_CPU1):
        cv.add(frame(X_SOCK, y, SOCKET_W, SOCKET_H, 4, 0.30))
        cv.add(frame(X_SOCK + 14, y + 14, SOCKET_W - 28, SOCKET_H - 28, 2, 0.20))
        cv.add(label(X_SOCK + SOCKET_W / 2, y + SOCKET_H / 2 + 5, "CV", 15))

    # Блоки питания. Шильдик — наклейка: светлая плашка с чёрной рамкой, внутри
    # знаки питания и номер отсека. Рамка у первого сплошная, у второго
    # пунктирная: на крышке два одинаковых шильдика, и различает их только она.
    for n, y in enumerate(PSU_Y):
        cv.add(frame(X_REAR, y, PSU_W, PSU_H, 0, 0.26))
        cy = y + PSU_H / 2
        px, py = PLATE_CX - PLATE_W / 2, cy - PLATE_H / 2
        dash = '' if n == 0 else ' stroke-dasharray="9 7"'
        cv.add(f'<g transform="rotate(-90 {PLATE_CX} {cy})">'
               f'<rect x="{px}" y="{py}" width="{PLATE_W}" height="{PLATE_H}" rx="2" '
               f'fill="#e8e3d5" fill-opacity="0.82"/>'
               + rating_label(px + 4, py + 5, n + 1, w=116, h=36)
               + f'<text x="{px+PLATE_W-24}" y="{cy+4}" text-anchor="middle" fill="#161005" '
                 f'font-family="ui-monospace, Menlo, monospace" font-size="11" '
                 f'font-weight="700" letter-spacing="0.06em">PSU {n+1}</text>'
               + f'<rect x="{px}" y="{py}" width="{PLATE_W}" height="{PLATE_H}" rx="2" fill="none" '
                 f'stroke="#05090b" stroke-width="3.4"{dash}/>'
               + '</g>')

    # Райзеры и обвязка задних гнёзд. Обводки кончаются там, где начинается
    # перфорация: рамка, проведённая поверх дырок, читается краской по воздуху,
    # а не контуром узла под листом. Правый край у всех один — кромка поля сот,
    # левый тоже: они и на плате стоят в одной колонке, и разной ширины рамки
    # читались бы как узлы разного размера.
    BLOCK_X = X_REAR + 12
    BLOCK_W = (X_IO - 8) - BLOCK_X
    for y, hh in RISER:
        cv.add(frame(BLOCK_X, y, BLOCK_W, hh, 6, 0.22))
    # Рамка обводит то, что стоит на плате за гнёздами: магнитопроводы, PHY и
    # лапки кожухов. Прежний габарит в 234 единицы повторял выдуманную плату
    # встроенных интерфейсов, и после её сноса крышка обводила бы пустое место.
    # Той же ширины и от того же левого края, что и рамки райзеров: на плате
    # это соседи в одной колонке, и разнобой в габаритах читался бы как разные
    # по величине узлы.
    cv.add(frame(BLOCK_X, IO_BOARD[1], BLOCK_W, IO_BOARD[3], 3, 0.24))
    # Сами гнёзда крышка не обводит, и это не пропуск: они стоят ровно под
    # перфорацией, и рамка, нарисованная поверх сот, читалась бы краской по
    # воздуху. Видно их и так — сквозь дырки, вместе с мигающими лампами.

    # Ссылки стоят там же, где выноски на самой схеме: гнёзда SFP+ — на торце
    # карты в верхнем райзере, остальное — против середины своего гнезда.
    cv.add(label(X_IO - 30, RISER[0][0] + 44, "LinkedIn", 12, anchor_="end"))
    for k, name in enumerate(("Telegram", "Twitter", "Email")):
        cv.add(label(X_IO - 30, IO_Y + k * JACK_PITCH + JACK_H / 2 + 4, name, 12, anchor_="end"))

    # Сервисные наклейки. Колонка вдоль стенки вентиляторов освободилась
    # целиком — саму стенку крышка больше не рисует, — и обе наклейки, которые
    # раньше стояли в ней поперёк и упирались в верхний край, теперь лежат
    # вдоль: развёрнуты на 90° против часовой, читаются снизу вверх и разнесены
    # по высоте. Ниже них по крышке ничего нет, так что тесниться незачем.
    front_cx = X_FAN + FAN_W / 2

    def turned(cx, cy, w, h, draw):
        """Наклейка, положенная вдоль крышки: рисуем как обычно и поворачиваем."""
        return (f'<g transform="rotate(-90 {cx} {cy})">'
                + draw(cx - w / 2, cy - h / 2, w, h) + '</g>')

    # Легенда — про сам цветовой код, без неё шапки остальных наклеек нечем
    # прочесть, поэтому она стоит первой и ничему конкретному не подчинена.
    cv.add(turned(front_cx, 240, 182, 86,
                  lambda x, y, w, h: service_legend(x, y, w, h)))

    # Диски: горячая замена, поэтому терракотовая шапка. Стрелка — куда
    # каддик едет наружу, то есть к фронту, а фронт у нас слева по глубине.
    # После поворота «наружу» смотрит вниз, к нижнему краю крышки.
    cv.add(turned(front_cx, 585, 232, 104,
                  lambda x, y, w, h: service_label(
                      x, y, w, h, "HOT-SWAP HDD",
                      ["① откинуть ручку каддика",
                       "② вынуть каддик наружу"],
                      arrow="left")))

    # Наклейки узлов стоят в полосе между банками памяти и отсеками БП, каждая
    # на высоте своего узла: читать её можно не гадая, к чему она относится.
    back_x = X_CORE + DIMM_SOCK_W + 14
    back_w = X_REAR - 8 - back_x

    # Память: своя высота — та же, что у рамки банка L, посчитанная теми же
    # BANK_N и PITCH, что и сама рамка чуть выше.
    cv.add(service_label(back_x, Y_BANK_L - 1, back_w, bank_h, "MEMORY",
                         ["① развести защёлки",
                          "② вынуть планку",
                          "NOTE: сначала по слоту на канал"],
                         head=COLD))

    # Процессоры: обесточив, поэтому голубая шапка. Attention — про то, что
    # ножки сокета живые и гнутся, если рычаг откидывать неаккуратно.
    cv.add(service_label(back_x, Y_CPU0, back_w, SOCKET_H, "PROCESSOR",
                         ["① снять радиатор",
                          "② откинуть рычаг сокета",
                          "③ вынуть процессор",
                          "Attention: контакты сокета гнутся"],
                         head=COLD))

    # Блоки питания. Вровень с нижним отсеком эта наклейка стоять больше не
    # может: там же лежит кнопка снятия крышки, и кнопка накрывала её целиком.
    # Поднята ровно настолько, чтобы кончиться выше кнопки.
    cv.add(service_label(back_x, LID_BTN[1] - 20 - PSU_H, back_w, PSU_H, "POWER SUPPLY",
                         ["① зажать фиксатор",
                          "② потянуть за ручку"]))

    # Марка листа — у самой нижней кромки: выше неё проходит рамка правого
    # банка, и на прежней высоте строка ложилась прямо на её нижнюю сторону.
    cv.add(label((LID_X + W) / 2, H - 12, "CD93-FS1  ·  SERVICE COVER", 11, op=0.26))
    # кнопка снятия — на крышке, в тех же координатах, что кнопка «надеть» на
    # плате: место не прыгает, меняется только надпись
    bx, by, bs = LID_BTN
    # Рисунок пересчитан от стороны квадрата: кнопка выросла, и отступы обязаны
    # вырасти вместе с ней — иначе стрелка с подписью останутся в прежнем углу
    # увеличенной рамки, а на плате точно такая же кнопка нарисована по тем же
    # долям, и разъезжаться им нельзя.
    k = bs / 86
    # Доли по вертикали — те же, что у «надеть»: значок в полосе 22…46, строки
    # на 66 и 78. Здесь всё содержимое стояло ниже, и нижняя строка приходилась
    # ровно на 86 — то есть на саму нижнюю кромку рамки, надпись лежала на
    # линии. Одна и та же кнопка в двух состояниях не имеет права выглядеть
    # по-разному, и рисунок отличается от «надеть» только направлением стрелки.

    # Синие защёлки на передней кромке листа. Это они и снимают крышку: на
    # живой машине сперва давят на них, и только потом лист идёт назад. Поэтому
    # они лежат внутри той же кнопки, а не рядом с ней — отдельной кнопкой они
    # были бы третьим изображением одного действия, и вдобавок потребовали бы
    # своего обработчика в общем скрипте.
    latches = ''.join(
        f'<g class="lid-latch">'
        f'<rect x="{LID_X+6}" y="{ly}" width="24" height="52" rx="3" fill="{COLD}" '
        f'stroke="rgba(238,232,213,0.55)" stroke-width="1.2"/>'
        + ''.join(f'<line x1="{LID_X+11}" y1="{ly+12+g*10}" x2="{LID_X+25}" y2="{ly+12+g*10}" '
                  f'stroke="rgba(238,232,213,0.34)" stroke-width="1.6"/>' for g in range(4))
        + '</g>' for ly in (H * 0.22 - 26, H * 0.78 - 26))
    cv.add(f'<g id="lid-remove" class="lid-btn-svg" role="button" tabindex="0" aria-label="Снять крышку">'
           f'<rect x="{bx}" y="{by}" width="{bs}" height="{bs}" rx="4" fill="#1b2429" '
           f'stroke="rgba(147,161,161,0.5)" stroke-width="1.6"/>'
           f'<path d="M{bx+26*k:.0f} {by+34*k:.0f} h{34*k:.0f} M{bx+43*k:.0f} {by+46*k:.0f} '
           f'v{-24*k:.0f} m{-8*k:.0f} {8*k:.0f} l{8*k:.0f} {-8*k:.0f} {8*k:.0f} {8*k:.0f}" fill="none" '
           f'stroke="rgba(147,161,161,0.6)" stroke-width="{2*k:.1f}"/>'
           + label(bx + 43 * k, by + 66 * k, "СНЯТЬ", 9 * k, op=0.7)
           + label(bx + 43 * k, by + 78 * k, "КРЫШКУ", 9 * k, op=0.7)
           + latches + '</g>')
