"""шкаф над машиной: два коммутатора и патч-корды к ним.

Единственный блок схемы, который рисует не машину. Всё, что здесь есть,
стоит НАД ней и в неё не входит: стойка, десятигигабитный коммутатор,
обычный гигабитный и три кабеля от задней панели к ним.

Зачем это на схеме вообще. Три гнезда машины уводят на три чужих адреса, и
до сих пор щелчок по ним срабатывал мгновенно — гость видел переход, но не
видел, куда в понятиях самой машины уходит её трафик. Сцена открытия ведёт
камеру от гнезда по кабелю до той железки, в которую он воткнут, и разница
между десятью гигабитами и одним перестаёт быть надписью: это две разные
железки на двух разных полках.

Почему это в той же схеме и в тех же координатах. Камера сцены — viewBox, и
ничего, кроме viewBox, она не трогает. Значит доехать до шкафа можно, если
шкаф лежит в той же системе координат просто выше рамки: никакого второго
SVG, никакой обёртки с transform и никакого пересчёта обрезок. Координаты в
geom, как у всего остального.

Место на плате блок не занимает и в регистр занятости не пишет НИЧЕГО — и
это не забывчивость. Регистр отвечает на вопрос «что стоит на текстолите»;
шкаф не стоит на нём вовсе, и бронь под него значила бы, что на плате есть
место, куда нельзя ставить деталь. Такого места нет.

Видимость — забота css. У схемы `overflow: visible`, то есть нарисованное
выше рамки просмотра рисуется поверх страницы, а не отсекается ею: шкаф,
оставленный видимым, лёг бы прямо на заголовок. Поэтому по умолчанию он
скрыт и показывается только своей сценой (rack.css, rack.js).
"""

# Свой прямоугольник — весь в отрицательных Y, над машиной. Он шире самого
# шкафа сверху и снизу: над стойкой стоит её подпись, под стойкой — номер
# детали, и оба выходят за железо, как и на остальных узлах схемы.
#
# Кабели в габарит не входят нарочно: они нарисованы путями, а сборка считает
# габариты по координатным атрибутам и `d` не разбирает.
BOUNDS = (892, -984, 540, 888)

from board.geom import (
    NET_LANE,
    NET_PORT,
    RACK_H,
    RACK_POST,
    RACK_SLOTS,
    RACK_U,
    RACK_U0,
    RACK_W,
    RACK_X,
    RACK_Y,
    SW_1G_Y,
    SW_10G_Y,
    SW_H,
    SW_PAD,
    SW_SLOT,
    SW_W,
    SW_X,
    X_NET_OUT,
    sw_port_x,
)
from board.ink import mono
from board.lamps import lamp
from board.palette import CHASSIS, METAL, METAL_DEEP, STEEL
from board.revision import stamp
from board.spec import NET_UPLINK, SWITCHES

# Куда по вертикали приходит кабель у каждого коммутатора: в нижнюю кромку
# корпуса, то есть с той стороны, с которой к нему поднимаются провода.
SW_Y = {'sw10': SW_10G_Y, 'sw1': SW_1G_Y}


def _port_seats():
    """Середина того гнезда машины, из которого выходит кабель.

    У гигабитной пары честно: IO_Y, JACK_PITCH и JACK_H — это те же константы
    geom, по которым rear_io рисует сами розетки.

    NOTE: у карты OCP не так. Её раскладка повторена здесь по частям — `+6`,
    `-46` и `+2` risers.py считает у себя вторым экземпляром, а общего у нас
    только RISER и BRACKET_W. Сцепка молчаливая: сдвинь карту в risers, и
    кабель отцепится от гнезда, не сказав об этом никому — кабель нарисован
    путём, а габариты сборка считает по координатным атрибутам и `d` не
    разбирает. Развязывается это переносом смещений торца карты в geom, но
    вместе с правкой risers; пока держится тем, что раскладку карты не трогают.
    """
    from board.geom import BRACKET_W, IO_Y, JACK_H, JACK_PITCH, RISER

    # Карта OCP: её торец — верхнее гнездо SFP+. Тот же счёт, что в risers.
    edge_y = RISER[0][0] + BRACKET_W + 6
    card_y = edge_y - 46
    return {'ocp': card_y + 2 + 11,
            'eth': IO_Y + 0 * JACK_PITCH + JACK_H / 2,
            'tw': IO_Y + 1 * JACK_PITCH + JACK_H / 2}


def _ports(sw_id):
    return next(w['ports'] for w in SWITCHES if w['id'] == sw_id)


# Кабель воткнут в гнездо, которого может не оказаться. Сверка паспорта этого
# не ловит: она считает СУММУ гнёзд по обеим железкам, и перенос портов с
# одной на другую проходит молча — а патч-корд при этом уезжает мимо морды и
# за пределы шкафа. Проверка живёт здесь, а не в geom: число портов лежит в
# паспорте, а geom о паспорте не знает — это spec импортирует geom, не наоборот.
for _group, _sw in NET_UPLINK.items():
    assert NET_PORT[_group] < _ports(_sw), (
        f'{_group}: кабель воткнут в гнездо {NET_PORT[_group]}, '
        f'а на {_sw} их всего {_ports(_sw)}')


def cable(group, sw_id):
    """Патч-корд от гнезда машины до гнезда коммутатора.

    Ход у кабеля тот же, что и на живой стойке: наружу от гнезда, вверх по
    своей дорожке и заворот в морду коммутатора. Прямой линии здесь быть не
    может — у кабеля есть радиус изгиба, и ломаная под прямым углом читалась
    бы дорожкой на плате, а не проводом.
    """
    sy = _port_seats()[group]
    lane = NET_LANE[group]
    ty = SW_Y[sw_id] + SW_H                      # нижняя кромка корпуса
    tx = sw_port_x(NET_PORT[group], _ports(sw_id))
    sx = X_NET_OUT
    return (f'M{sx} {sy:.1f} '
            f'C{sx + 46} {sy:.1f} {lane} {sy - 40:.1f} {lane} {sy - 110:.1f} '
            f'L{lane} {ty + 96} '
            f'C{lane} {ty + 42} {tx + 30:.1f} {ty} {tx:.1f} {ty}')


def blank(y):
    """Заглушка в свободном юните.

    На живой стойке открытых дыр не оставляют: воздух пошёл бы мимо железа,
    а не сквозь него. Заглушка — штампованный лист с двумя вырезами под
    пальцы, и рисовать в ней больше нечего.
    """
    return (f'<rect x="{SW_X}" y="{y}" width="{SW_W}" height="{SW_H}" rx="3" '
            f'fill="{METAL_DEEP}" stroke="rgba(147,161,161,0.16)"/>'
            + ''.join(
                f'<rect x="{SW_X + SW_W / 2 + dx - 26}" y="{y + SW_H / 2 - 5}" '
                f'width="52" height="10" rx="3" fill="#05090b" fill-opacity="0.55"/>'
                for dx in (-92, 92)))


def switch(w):
    """Коммутатор на полке: морда с подписью, решётка, ряд гнёзд и лампы.

    Гнёзда расставлены по той же формуле, по которой посчитан конец кабеля
    (`sw_port_x`), и столько их, сколько обещано в паспорте. Сборка это
    проверяет: `data-swport` она считает и сверяет с EXPECT — соврать о числе
    портов можно теперь только в паспорте и на морде одновременно.
    """
    y, n = SW_Y[w['id']], w['ports']
    out = [f'<rect x="{SW_X}" y="{y}" width="{SW_W}" height="{SW_H}" rx="4" '
           f'fill="{METAL}" stroke="rgba(147,161,161,0.38)"/>']

    # Морда делится надвое: слева шильдик с подписью, справа решётка. Одним
    # полем во всю ширину она читалась пустой коробкой — на живой железке
    # заводская наклейка занимает ровно левую треть, а остальное дышит.
    plate_w = SW_W * 0.60
    out.append(f'<rect x="{SW_X + 10}" y="{y + 9}" width="{plate_w}" height="46" rx="2.5" '
               f'fill="#0c161b" stroke="rgba(42,161,152,0.26)"/>')
    grille_x = SW_X + 10 + plate_w + 14
    grille_w = SW_X + SW_W - 12 - grille_x
    out += [f'<rect x="{grille_x + k * 7:.1f}" y="{y + 12}" width="3" height="40" rx="1.5" '
            f'fill="#05090b" fill-opacity="0.6"/>'
            for k in range(int(grille_w // 7))]

    # Ряд гнёзд по нижней кромке: кабель приходит снизу, оттуда же, где стоит
    # машина. Ширина гнезда берётся от шага, а не своим числом — у
    # десятигигабитного их восемь на ту же морду, и клетка втрое шире.
    pitch = (SW_W - 2 * SW_PAD) / n
    pw, ph = pitch * 0.62, 13
    for i in range(n):
        cx = sw_port_x(i, n)
        out.append(f'<rect class="swport" data-swport="{w["id"]}-{i}" '
                   f'x="{cx - pw / 2:.1f}" y="{y + SW_H - ph - 6}" '
                   f'width="{pw:.1f}" height="{ph}" rx="1.4" '
                   f'fill="#0a1418" stroke="rgba(42,161,152,0.38)" stroke-width="0.8"/>')

    # Лампа линка у каждого гнезда — одна, а не две: на морде коммутатора их
    # и печатают по одной на порт, вторая живёт в самой розетке.
    out += [lamp('led-link', sw_port_x(i, n), y + SW_H - ph - 13, 2.0, '#859900')
            for i in range(n)]

    out += [mono(SW_X + 22, y + 30, w['label'], 15, anchor='start', op=0.78),
            mono(SW_X + 22, y + 47, f"{w['model']} · {n}× {w['media']}", 8.5,
                 anchor='start', op=0.44),
            mono(SW_X + 2 + plate_w, y + 30, w['rate'], 10, anchor='end', op=0.55)]

    return f'<g class="sw sw-{w["id"]}" data-sw="{w["id"]}">' + ''.join(out) + '</g>'


def render(cv):
    # Стойка: две рейки с монтажными отверстиями. Рисуется она бедно нарочно —
    # это фон для двух железок, а не предмет разглядывания: подробная стойка
    # перетянула бы на себя весь кадр, ради которого сцена и едет наверх.
    x1 = RACK_X + RACK_W - RACK_POST
    y1 = RACK_Y + RACK_H
    frame = [
        f'<rect x="{RACK_X}" y="{RACK_Y}" width="{RACK_W}" height="{RACK_H}" rx="6" '
        f'fill="{CHASSIS}" stroke="rgba(147,161,161,0.26)"/>',
        f'<rect x="{RACK_X}" y="{RACK_Y}" width="{RACK_POST}" height="{RACK_H}" '
        f'fill="{STEEL}"/>',
        f'<rect x="{x1}" y="{RACK_Y}" width="{RACK_POST}" height="{RACK_H}" '
        f'fill="{STEEL}"/>',
    ]
    # Монтажные отверстия реек. Шаг — треть юнита: на живой стойке их пробито
    # по три на юнит, и по ним же считают, куда встанет следующая железка.
    step = RACK_U / 3
    for k in range(int(RACK_H // step)):
        hy = RACK_Y + 14 + k * step
        if hy > y1 - 14:
            break
        for hx in (RACK_X + RACK_POST / 2, x1 + RACK_POST / 2):
            frame.append(f'<circle cx="{hx}" cy="{hy:.1f}" r="2.6" fill="#05090b" '
                         f'fill-opacity="0.7"/>')

    frame.append(mono(RACK_X + RACK_W / 2, RACK_Y - 14, 'ШКАФ · UPLINK', 12, op=0.34))

    # Юниты по порядку: где стоит железка — железка, где не стоит — заглушка.
    taken = {slot: sw_id for sw_id, slot in SW_SLOT.items()}
    shelves = []
    for k in range(RACK_SLOTS):
        if k in taken:
            shelves.append(switch(next(w for w in SWITCHES if w['id'] == taken[k])))
        else:
            shelves.append(blank(RACK_U0 + k * RACK_U))

    cv.add('<g class="rack">' + ''.join(frame) + ''.join(shelves)
           + stamp(RACK_X + 8, y1 + 16, 'rack') + '</g>')

    # Кабели. Каждый — своя группа: сцена показывает ровно тот, о котором
    # спросили, а не всю косу разом. Внутри две линии одним и тем же путём:
    # сам провод и бегущий по нему пакет.
    links = []
    for group, sw_id in NET_UPLINK.items():
        d = cable(group, sw_id)
        links.append(
            f'<g class="netlink" data-link="{group}" data-sw="{sw_id}">'
            f'<path class="net-cable" pathLength="100" d="{d}"/>'
            f'<path class="net-flow" pathLength="100" d="{d}"/>'
            f'</g>')
    cv.add('<g class="netlinks">' + ''.join(links) + '</g>')
