"""фронт: восемь отсеков 2.5″ четырьмя группами по два.

Диски в 1U ходят парами: два каддика в группе, между группами — стойка
корзины. Каддик занимает не всю глубину фронта: за ним видно нутро
корзины — направляющие и ответный разъём. Туда же диск и уезжает, когда
его вынимают, поэтому пустое место под ним не пустота, а посадочное место.

Каддик разобран на три части, и границы между ними — не рисунок, а
механика. Голова с лампами приклёпана к салазкам и никуда не девается.
Ручка — длинный рычаг во всю оставшуюся длину лицевой стороны: за него
берутся, он отгибается влево, и только после этого каддик идёт наружу.
Наклейка с моделью — на самой ручке, потому что на живом каддике лицевая
сторона и есть ручка, а больше наклеить некуда.
"""

# Свой прямоугольник: сборка проверит, что узел из него не вышел.
# Слева выходит за габарит шасси: вынутый диск выезжает наружу, как в жизни.
# Крайняя левая точка — не краска, а окно отсечения: оно обязано быть шире
# полного вылета каддика (152 единицы плюс отведённая ручка), иначе срез
# отрежет уехавшую рамку. Видимого следа за кромкой шасси у блока по-прежнему
# нет — там только вынутая деталь.
BOUNDS = (-220, 194, 400, 664)

from board.geom import (
    BAY_N,
    BAY_NUM_H,
    BAY_TOP,
    BAY_W,
    CAP,
    FRONT_W,
    GROUP_GAP,
    GROUP_H,
    X_FRONT,
    bay_seat,
)
from board.ink import silk_frame
from board.lamps import act_led, lamp
from board.spec import BAYS

LABEL_H = 43     # наклейка на ручке: вдвое короче прежнего шильдика
# Глубина накопителя. Он в разы длиннее своей лицевой панели — на то он и
# сидит внутри шасси, — и это единственное число, которым задаётся, насколько
# далеко каддик обязан выехать, чтобы диск стало видно целиком.
DRIVE_W = 96


def vent_slots(x, y, w, h, n=3):
    """Ряд продольных прорезей: через них каддик и дышит."""
    step = w / n
    return ''.join(
        f'<rect x="{x + c * step + 2:.1f}" y="{y}" width="{step - 4:.1f}" height="{h}" '
        f'rx="1.5" fill="#05090b" stroke="rgba(147,161,161,0.16)"/>'
        for c in range(n))


def caddy_head(x, y, w, lamps):
    """Голова каддика: лампы сверху, под ними решётка.

    Она приклёпана к салазкам, а не к ручке, поэтому остаётся на месте, когда
    ручку отгибают: на живом каддике светодиоды сидят на плате самого
    переходника и уезжают только вместе с диском.
    """
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{CAP}" rx="1" fill="#0d1317" '
            f'stroke="rgba(147,161,161,0.24)"/>'
            + lamps
            + vent_slots(x + 4, y + 22, w - 8, CAP - 28))


def drive_heatsink(x, y, h):
    """Радиаторное поле у дальнего торца — единственная деталь корпуса,
    которая на глаз отличает Optane от рядового U.2.

    P5800X греется куда сильнее обычной NVMe, и крышку над дальним торцом (там,
    где выходит разъём) вместо гладкого металла закрывает поле пин-рёбер,
    фрезерованных в самом теле корпуса. Каждое ребро — крест, и стоят они
    шахматно, через ряд со сдвигом: и то и другое ради продува. Крест при той
    же площади основания даёт вчетверо больше боковой поверхности, а шахматный
    сдвиг оставляет между рёбрами сквозные каналы по диагоналям.

    Требует `url(#fin-shade)`, определённый один раз в defs render() — общий
    градиент на все диски дешевле, чем свой на каждый пупырышек.
    """
    ink = 'rgba(147,161,161,'
    fw, side = 28, 7.5
    fx1 = x + DRIVE_W - 16    # заметно короче торца: голый металл виден и за полем
    fx0 = fx1 - fw
    fy0, fy1 = y + 6, y + h - 6
    fh = fy1 - fy0
    cols, pitch_x, pitch_y = 3, fw / 3, 13
    rows = int(fh // pitch_y)
    parts = [(f'<rect x="{fx0:.1f}" y="{fy0:.1f}" width="{fw}" height="{fh:.1f}" rx="1" '
              f'fill="#12181c" stroke="{ink}0.30)"/>')]
    for r in range(rows):
        shift = pitch_x / 2 if r % 2 else 0
        cy = fy0 + r * pitch_y + (pitch_y - side) / 2
        for c in range(cols):
            cx = fx0 + c * pitch_x + shift + (pitch_x - side) / 2
            if cx + side > fx1 - 1:
                continue    # шахматный сдвиг иногда выносит крайний столбец за поле
            # Ребро — крест, а не квадрат. Фрезеруют его именно так: у креста
            # при той же площади основания вчетверо больше боковой поверхности,
            # а между лучами соседних рёбер остаются сквозные каналы по обеим
            # диагоналям — сплошной квадратный столбик перекрыл бы их.
            a = side / 3
            parts.append(
                f'<path d="M{cx + a:.1f} {cy:.1f} h{a:.1f} v{a:.1f} h{a:.1f} v{a:.1f} '
                f'h-{a:.1f} v{a:.1f} h-{a:.1f} v-{a:.1f} h-{a:.1f} v-{a:.1f} h{a:.1f} Z" '
                f'fill="url(#fin-shade)"/>')
    # Блик по верхней кромке поля и тень по нижней — без них ряды пупырышков
    # тонут в общей темноте корпуса и читаются как штриховка, а не рельеф.
    parts.append(f'<rect x="{fx0:.1f}" y="{fy0:.1f}" width="{fw}" height="2" '
                 f'fill="rgba(210,214,214,0.16)"/>')
    parts.append(f'<rect x="{fx0:.1f}" y="{fy1-2:.1f}" width="{fw}" height="2" '
                 f'fill="rgba(5,9,11,0.40)"/>')
    return ''.join(parts)


def drive_body(x, y, h, lit=True, model='', size=''):
    """Сам накопитель — то, что сидит в шасси за лицевой панелью.

    Он глубже своей панели в несколько раз, и в собранной машине его не видно
    вовсе: наружу смотрит только рамка каддика. Поэтому он и появляется лишь
    когда каддик поехал наружу — до тех пор это деталь внутри корпуса, а не
    часть фронта.

    Крышка сверху, разъём питания и данных на дальнем торце, радиаторное поле
    рядом с ним, наклейка с ёмкостью — то, что видно, когда диск держишь в
    руках.
    """
    dw = DRIVE_W
    ink = 'rgba(147,161,161,'
    parts = [(f'<rect x="{x}" y="{y}" width="{dw}" height="{h}" rx="2" fill="#1c2329" '
              f'stroke="{ink}0.36)" stroke-width="1.6"/>')]
    if not lit:
        # Пустой каддик: салазки сверху и снизу, между ними ничего. Так и
        # выглядит заглушка, когда её вынешь, — рамка с направляющими и воздух.
        for ry in (y + 4, y + h - 10):
            parts.append(f'<rect x="{x+4}" y="{ry}" width="{dw-8}" height="6" rx="2" '
                         f'fill="#2b353c" stroke="{ink}0.30)"/>')
        parts[0] = (f'<rect x="{x}" y="{y}" width="{dw}" height="{h}" rx="2" fill="none" '
                    f'stroke="{ink}0.26)" stroke-width="1.2" stroke-dasharray="6 4"/>')
        return ''.join(parts)
    # Крышка прикручена по углам — четыре винта, как на любом 2.5″. Отступ до
    # неё шире, чем у обычной NVMe: у Optane сплошной металлический корпус, и
    # видимая рамка металла вокруг крышки — это его лишняя толщина и вес.
    parts.append(f'<rect x="{x+7}" y="{y+7}" width="{dw-14}" height="{h-14}" rx="1.5" '
                 f'fill="#28323a" stroke="{ink}0.22)"/>')
    # Лёгкий диагональный блик поверх крышки — фрезерованный металл, а не
    # крашеный пластик кожуха обычного диска.
    parts.append(f'<rect x="{x+7}" y="{y+7}" width="{dw-14}" height="{h-14}" rx="1.5" '
                 f'fill="url(#metal-sheen)"/>')
    parts.extend(f'<circle cx="{cx}" cy="{cy}" r="2" fill="#0d1317" stroke="{ink}0.34)"/>'
                 for cx in (x + 9, x + dw - 9) for cy in (y + 9, y + h - 9))
    # Разъём на дальнем торце: питание и данные одной колодкой, как у U.2.
    parts.append(f'<rect x="{x+dw-13}" y="{y+h/2-16:.1f}" width="9" height="32" rx="1" '
                 f'fill="#14202a" stroke="rgba(42,161,152,0.34)"/>')
    parts.append(drive_heatsink(x, y, h))
    # Наклейка на крышке — то самое место, по которому диск и опознают в руках.
    # Модель приходит из паспорта: под какой отсек что стоит, знает он один.
    # Сужена под радиаторное поле рядом — раньше занимала всю крышку, теперь
    # делит её с рёбрами.
    # Прозрачность наклейки живёт в альфе самого цвета, а не в fill-opacity:
    # весь накопитель гасится наследуемым fill-opacity, а собственный атрибут
    # у ребёнка сильнее наследуемого значения — и наклейка оставалась светлым
    # пятном, просвечивающим сквозь решётку корзины.
    # Модель разложена по словам, по строке на слово, и это не украшение.
    # Наклейка делит крышку с радиатором и шире сорока единиц быть не может, а
    # «INTEL OPTANE P5800X» одной строкой — это восемьдесят: она вылезала за
    # наклейку вдвое и уходила за левую кромку корпуса. Слова короткие, каждое
    # умещается с запасом.
    lines = [*model.split(), size]
    lx, ly, lw = x + 8, y + h / 2 - 4 - len(lines) * 11 / 2, 40
    parts.append(f'<rect x="{lx}" y="{ly:.1f}" width="{lw}" height="{len(lines) * 11 + 10}" '
                 f'rx="1.5" fill="rgba(232,227,213,0.10)" stroke="{ink}0.26)"/>')
    for row, text in enumerate(lines):
        op = 0.62 if row < len(lines) - 1 else 0.42
        parts.append(f'<text x="{lx + lw / 2:.1f}" y="{ly + 16 + row * 11:.1f}" '
                     f'text-anchor="middle" fill="{ink}{op})" '
                     f'font-family="ui-monospace, Menlo, monospace" font-size="7">{text}</text>')
    return ''.join(parts)


def dark_lamps(x, y):
    """Те же две лампы, что у живого каддика, только потухшие.

    Рисуем их, а не выбрасываем: на заглушке светодиоды физически стоят, и
    пустое место на их месте читалось бы другой деталью, а не тем же каддиком
    без диска.
    """
    return ''.join(
        f'<circle cx="{cx}" cy="{y + 11}" r="2.5" fill="#1d262b" '
        f'stroke="rgba(147,161,161,0.22)"/>'
        for cx in (x + 10, x + 23))


def render(cv):
    # Общие градиенты для тела диска: один на все восемь, а не свой на
    # каждый пупырышек радиатора — так же, как «die-shine» у процессоров.
    # fin-shade лепит рельеф пин-ребра без пары теневых прямоугольников на
    # каждый — светлый угол и тёмный по диагонали уже есть в самой заливке.
    # metal-sheen — тот же приём для крышки целиком: одна лёгкая диагональ
    # вместо кучи полос, а читается как фрезерованный металл.
    cv.add('<defs>\n'
        # Проценты вместо долей 0..1 — не ради вида: сборка меряет габарит
        # блока по числам в атрибутах x1/y1/x2/y2, и "0"/"1" у градиента
        # читались бы как точка (0,0) в его координатах, раздувая BOUNDS.
        '  <linearGradient id="fin-shade" x1="0%" y1="0%" x2="100%" y2="100%">\n'
        '    <stop offset="0%"  stop-color="#aab4b4" stop-opacity="0.55"/>\n'
        '    <stop offset="55%" stop-color="#4d5a5f" stop-opacity="0.4"/>\n'
        '    <stop offset="100%" stop-color="#060a0c" stop-opacity="0.6"/>\n'
        '  </linearGradient>\n'
        '  <linearGradient id="metal-sheen" x1="0%" y1="0%" x2="100%" y2="100%">\n'
        '    <stop offset="0%"   stop-color="#dce0e0" stop-opacity="0.10"/>\n'
        '    <stop offset="35%"  stop-color="#dce0e0" stop-opacity="0"/>\n'
        '    <stop offset="100%" stop-color="#dce0e0" stop-opacity="0"/>\n'
        '  </linearGradient>\n'
        '</defs>')
    # Нутро корзины — та же перфорированная стенка, что и на фронте, и рисует
    # её фронт: лист там один, буквой Г, и полоса вдоль корзины — его часть.
    # Своя решётка тут была ровно до тех пор, пока фронт и корзина считались
    # разными деталями; от неё оставались подложка со своей обводкой и глухая
    # перемычка над корзиной.
    #
    # Здесь остаётся то, что к листу не относится: направляющие и ответные
    # разъёмы по отсекам. Их видно на месте вынутого диска — без них «вынуто»
    # читается дыркой в корпусе.
    for i in range(BAY_N):
        g, k = i // 2, i % 2
        x = X_FRONT + k * BAY_W
        slot_y = BAY_TOP + g * (GROUP_H + GROUP_GAP)
        # Верхняя полоса группы отдана нумерации: номер стоит на корзине, у
        # верхней грани своего каддика, и остаётся на месте, когда диск вынут.
        y = slot_y + BAY_NUM_H
        h = GROUP_H - BAY_NUM_H
        # Каддик занимает отсек целиком: посадочное место ровно под ним, и
        # видно его только когда диск вынут. Рамка короче гнезда читалась как
        # деталь, торчащая из чужого места, а не как вставленный диск.
        w = BAY_W - 3
        # Отсек занят каддиком целиком — тот же случай, что у памяти и райзеров:
        # узел нарисован, а регистр про него молчит.
        cv.busy(x, y, w, h, pad=0)

        # Направляющая и ответный разъём — то, что видно на месте вынутого
        # диска. Без них «вынуто» читается как дырка в корпусе.
        cv.add(f'''<g class="decor bay-slot">
      <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="1" fill="#0c1216"
            stroke="rgba(147,161,161,0.16)"/>
      <line x1="{x + 3}" y1="{y + 5}" x2="{x + w - 3}" y2="{y + 5}"
            stroke="rgba(147,161,161,0.20)" stroke-width="2"/>
      <line x1="{x + 3}" y1="{y + h - 5}" x2="{x + w - 3}" y2="{y + h - 5}"
            stroke="rgba(147,161,161,0.20)" stroke-width="2"/>
      <rect x="{x + w - 16}" y="{y + h / 2 - 20}" width="10" height="40" rx="1"
            fill="#14202a" stroke="rgba(42,161,152,0.30)"/>
      {silk_frame(x + w / 2 - 6, slot_y + 1, str(i), 7, 0.55)}
    </g>''')

        spec_bay = BAYS[i]
        filler = bool(spec_bay.get('filler'))

        # Каддик: салазки, накопитель в них и голова с лампами. Лампы наверху,
        # у самой грани: на живой корзине их читают сверху вниз одним взглядом,
        # а не выискивают у каждого диска в своём углу. У заглушки лампы те же,
        # только потухшие: гореть в ней нечему.
        lamps = dark_lamps(x, y) if filler else (
            act_led(i, x + 10, y + 11, 2.5, "#859900")
            + lamp("led", x + 23, y + 11, 2.5, "#b58900"))
        # Накопитель стоит за лицевой панелью, в глубине шасси. В собранной
        # машине его не видно вовсе, поэтому и рисуется он справа от рамки — на
        # своём настоящем месте, а показывается только когда каддик поехал
        # наружу.
        # Ёмкость, а не повтор модели. Развилка «для Optane пишем P5800X» имела
        # смысл, пока Optane стоял в одном отсеке из восьми; теперь такие все,
        # и наклейка дважды повторяла бы то, что уже написано строкой выше.
        # У заглушки на наклейке не написано ничего: это глухая панель, и
        # писать на ней нечего. Слово FILLER было подписью к пустоте.
        kind = '' if filler else spec_bay.get('kind', '')
        size = '' if filler else f"{spec_bay.get('tb', 0)} TB"
        # Накопитель нарисован на своём настоящем месте — справа от рамки, в
        # глубине шасси, — и обрезан по устью отсека. Пока каддик на месте,
        # диск целиком лежит правее среза и не виден; поехал наружу — и он
        # выезжает из устья, как выезжает в жизни.
        #
        # Отсечение сидит на неподвижной обёртке вокруг всего каддика: срез
        # стоит на месте, а внутри него едет одна группа — и рамка, и диск, и
        # ручка. Будь clip-path на движущемся узле, он ехал бы вместе с ним и
        # не обрезал бы ничего. Раньше диск просто проявлялся прозрачностью —
        # деталь не выезжала, а включалась.
        #
        # Правая кромка окна — устье отсека: диск нарисован сразу за ней и в
        # собранной машине не виден вовсе. Левая отнесена за габарит вылета,
        # иначе на полном ходу срез отрезал бы уехавшую рамку.
        clip = (f'<clipPath id="bay-out-{i}">'
                f'<rect x="-220" y="{y-8}" width="{x+w+220}" height="{h+16}"/></clipPath>')
        drive = (f'<g class="drive-body">'
                 f'{drive_body(x + w, y + 2, h - 4, lit=not filler, model=spec_bay.get("model", ""), size=size)}'
                 f'</g>')
        sled = [(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="1" fill="#28323a" '
                 f'stroke="rgba(147,161,161,0.26)"/>')]
        sled.append(caddy_head(x, y, w, lamps))

        # Ручка — отдельная деталь и главная на лицевой стороне: рычаг во всю
        # длину каддика. Сначала отщёлкивается она, и только потом диск идёт
        # наружу. Терракотовая планка — та самая защёлка, которую нажимают
        # большим пальцем; лежит она поперёк ручки, у самой её кромки, потому
        # что палец давит на неё сверху вниз, а не вдоль.
        hx, hy = x + 3, y + CAP + 4
        hw, hh = w - 6, h - CAP - 12
        lab_y = hy + hh - LABEL_H - 4
        handle = (f'<rect x="{hx}" y="{hy}" width="{hw}" height="{hh}" rx="3" '
                  f'fill="#0d1317" stroke="rgba(147,161,161,0.30)" stroke-width="1.2"/>'
                  f'<rect x="{hx+3}" y="{hy+4}" width="{hw-6}" height="9" rx="2" fill="#cb4b16" '
                  f'stroke="rgba(238,232,213,0.45)" stroke-width="1"/>'
                  # вентиляционные окна: воздух идёт к диску сквозь ручку
                  + vent_slots(hx + 4, hy + 19, hw - 8, lab_y - hy - 25, n=2))

        # Наклейка с моделью — на ручке, в её нижней половине. Строка идёт
        # вдоль каддика: он узкий, и поперёк она вылезала на соседей. Читается
        # сверху вниз — так же, как номера отсеков и всё остальное на фронте.
        # Отступы одинаковые с обеих сторон: раньше слева было 10, справа 4 —
        # наклейка сидела не по центру ручки, и повёрнутый текст (две строки
        # вбок от центра) обрезался правым краем.
        lab_x, lab_w = hx + 3, hw - 6
        handle += (f'<rect x="{lab_x}" y="{lab_y}" width="{lab_w}" height="{LABEL_H}" rx="1" '
                   f'fill="#e8e3d5" fill-opacity="0.09" stroke="rgba(147,161,161,0.24)"/>')
        tx, ty = lab_x + lab_w / 2, lab_y + LABEL_H / 2
        for ddx, text, size_pt, op in ((5, kind, 7, 0.55), (-6, size, 7, 0.4)):
            handle += (f'<text x="{tx+ddx:.1f}" y="{ty:.1f}" '
                       f'transform="rotate(90 {tx+ddx:.1f} {ty:.1f})" text-anchor="middle" '
                       f'fill="rgba(147,161,161,{op})" '
                       f'font-family="ui-monospace, Menlo, monospace" '
                       f'font-size="{size_pt}">{text}</text>')

        # Ручка лежит внутри тела, а не рядом с ним. Пока она была сестрой,
        # каддик разъезжался: подсветка при наведении поднимала тело и не
        # трогала ручку, а вынимание везло их разными правилами и они ехали
        # порознь. Теперь наружу едет вся деталь целиком, а ручка внутри неё
        # умеет ровно одно — откидываться.
        kind_cls = 'blank' if filler else 'bay'
        unit = f'blank{i}' if filler else f'hdd{i}'
        cv.add(f'''<g class="unit pick {kind_cls}" data-unit="{unit}" data-group="hdd"
          style="--seat:{bay_seat(i, filler)}" data-href="https://github.com/cosmdandy">
      {clip}
      <g clip-path="url(#bay-out-{i})">
        <g class="pick-body">{drive}{''.join(sled)}<g class="bay-handle">{handle}</g></g>
      </g>
    </g>''')
    # Выноска корзины — одна на все отсеки, и указывает она на диск, а не на
    # решётку рядом с ним: якорь сидит в середине каддика третьей группы.
    # В третьей группе внешний отсек занят заглушкой, поэтому целимся во
    # внутренний: выноска обязана указывать на диск, а не на пустую панель.
    hdd_y = BAY_TOP + 2 * (GROUP_H + GROUP_GAP) + GROUP_H / 2
    cv.callouts.append((X_FRONT + FRONT_W + 30, hdd_y, X_FRONT + BAY_W + (BAY_W - 3) / 2, hdd_y,
                     "GitHub", "start", "https://github.com/cosmdandy", "hdd",
                     "код и проекты", "github"))

