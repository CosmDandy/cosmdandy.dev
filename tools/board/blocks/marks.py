"""Обозначения разъёмов: refdes рядом со своим гнездом.

На живой плате у каждого разъёма напечатан его номер по схеме — `BAT1`,
`J30`, `P1`. Инженер находит гнездо именно по нему: назначение печатают
редко и не всем, а номер есть у всех, потому что по нему разъём ищут в
документации.

Раньше здесь лежал список из тринадцати строк с координатами, записанными
руками, и не вставала из него ни одна. Причины было три, и все три видно,
если спросить регистр занятости, кто именно мешает:

* координаты приходились на сами узлы — «PWR_CONN» просился ровно туда, где
  стоит колодка питания, и регистр честно отвечал «занято корпусом»;
* повёрнутая надпись рисуется вверх от своей точки, а точкой брался верхний
  край райзера — строка уходила в вырез под блок питания, где текстолита
  нет вовсе;
* восемь названий из тринадцати к этому времени печатали сами узлы
  («SLIMSAS → BP», «RISER_1 · PCIE_G5», «2× 1GbE», заголовки банков), а три
  — M.2, внутренний USB и кнопка NMI — называли то, чего на этой плате нет.

Поэтому координаты сюда больше не переписываются. Узел объявляет свой
габарит и свой номер через `cv.refdes()`, а место под надпись ищется вокруг
габарита — по расширяющимся кольцам, начиная вплотную к корпусу.

Блок стоит в очереди почти последним нарочно: до него плату занимают все,
и только здесь известно, с какой стороны у гнезда свободно.
"""

from board.canvas import BOARD, MAJOR, PART, SILK
from board.ink import silk_frame

# Чего избегает обозначение узла: всё, что избегает корпус, плюс чужая краска.
AVOID_MARK = (BOARD, MAJOR, PART, SILK)

SIZE = 6                 # кегль: на живой плате номер мельче названий узлов
GAPS = (2, 7, 13, 20)    # на сколько отступаем от кромки, если вплотную занято
SHIFTS = (0, 8, -8, 18, -18, 30, -30, 44, -44)


def frame_size(text, size=SIZE):
    """Габарит рамки обозначения — тот же расчёт, что в silk_frame."""
    return len(text) * size * 0.62 + 8, size + 6


def spots(x, y, w, h, tw, th):
    """Куда можно поставить обозначение у гнезда (x, y, w, h).

    Кольцами: сначала все четыре стороны вплотную, потом все четыре на шаг
    дальше. Кольцами, а не стороной за стороной, потому что номер печатают
    рядом с разъёмом, и «на два шага правее» хуже, чем «вплотную снизу».

    Сдвиг вдоль стороны нужен всерьёз: у гнезда, зажатого соседями, свободна
    бывает не сторона целиком, а её край.

    Возвращает точку рисования и флаг поворота. Повёрнутая рамка растёт вверх
    от своей точки, поэтому занятый ею прямоугольник считается отдельно.
    """
    for gap in GAPS:
        for shift in SHIFTS:
            yield x + shift, y - th - gap, False
            yield x + shift, y + h + gap, False
            yield x + w + gap, y + tw + shift, True
            yield x - th - gap, y + tw + shift, True


def box(px, py, tw, th, turn):
    """Прямоугольник, который займёт рамка, поставленная в (px, py).

    Повёрнутая рисуется через rotate(-90) вокруг своей точки, то есть уходит
    вверх и вправо от неё: ширина строки ложится на высоту.
    """
    return (px, py - tw, th, tw) if turn else (px, py, tw, th)


def render(cv):
    marks = []
    lost = []
    for (x, y, w, h), ref in cv.share.get('refdes', ()):
        tw, th = frame_size(ref)
        for px, py, turn in spots(x, y, w, h, tw, th):
            # Плашка узла — краска, но место под ней держим как под корпусом:
            # иначе рассыпуха ляжет сверху. А сама она на чужую краску залезать
            # не должна — «корпус» шелкографию не избегает, и плашки садились
            # на подпись «FAN FAULT» и на соседние обозначения.
            if cv.put(*box(px, py, tw, th, turn), avoid=AVOID_MARK):
                marks.append(silk_frame(px, py, ref, SIZE, turn=turn))
                break
        else:
            lost.append(ref)
    if marks:
        cv.add('<g class="decor silk">' + ''.join(marks) + '</g>')
    # Молчаливая потеря обозначений — это ровно то, чем болел прежний список:
    # тринадцать строк в коде и ноль на плате, и узнать об этом можно было
    # только пересчитав надписи в собранном SVG.
    # По находке на строку, а не одной строкой через запятую: список читают
    # не только глазами. tools/layers.py сверяет его с базой поимённо, и
    # склеенная строка меняла бы ключ целиком от каждой правки — в том числе
    # от такой, где половина обозначений как раз нашла себе место.
    for ref in lost:
        cv.lost.append('обозначение ' + ref)

    # Заглушек «мелочь по свободным карманам» здесь больше нет.
    #
    # Их было сорок семь: серый прямоугольник, кружок и прямоугольник с
    # рамкой, разбросанные псевдослучайно по всей плате. Ни одна не изображала
    # ничего — ни детали с выводами, ни отверстия, ни площадки, — и читались
    # они ровно тем, чем были: дырками. Лезли при этом всюду, включая поле под
    # процессором и надписи гнёзд памяти.
    #
    # Настоящая рассыпуха рисуется в pcb_scatter: у неё есть корпус, площадки
    # под пайку и своё место у той микросхемы, которую она обвязывает. Эти же
    # заглушки её только глушили — на плате становилось не гуще, а грязнее.
