"""контур жидкостного охлаждения: трубки от водоблоков к задней стенке.

Водоблоки рисует `cpu` — они сидят на процессорах и уезжают вместе с ними в
своей группе. Здесь то, что их соединяет: перемычка между блоками и две
магистрали к задней стенке.

Контур последовательный, и порядок в нём читается по трассе: подача входит в
правый штуцер первого блока, перемычка уводит жидкость к левому штуцеру
второго, обратка уходит от него назад. Параллельно оба блока не подключают —
второй получал бы холодную жидкость, а первый грелся бы вдвое.

Перемычка идёт слева, вдоль кромки памяти, а не напрямую между блоками:
между ними стоит средний банк, и труба через него прошла бы сквозь плашки.
На живой машине она обходит банк ровно так же — это и видно на фотографиях
двухпроцессорных сборок с DLC.

Трубки лежат поверх платы: они выше всего, что на ней распаяно, и прижаты к
ней клипсами. Поэтому блок рисуется после процессоров — накрывать он вправе.
"""

# Свой прямоугольник: сборка проверит, что узел из него не вышел.
BOUNDS = (470, 240, 826, 440)

import math
from math import cos, radians, sin

from board.geom import HUB_AT, RISER, SOCKET_H, SOCKET_W, TAP_LEN, TAPS
from board.geom import X_SOCK, X_WALL_FIELD, Y_CPU0, Y_CPU1
from board.ink import mono
from board.palette import COLD, STEEL, TUBE as TUBE_COLOR, TUBE_LIT

# Наружный диаметр трубки. Толще, чем кажется нужным: по контуру идёт вода под
# давлением, и шланг у неё армированный — тонкая линия читалась бы проводом,
# а провода на этой плате уже есть.
TUBE = 18
# Форма колена. Радиус — доля соседнего отрезка с потолком: постоянный радиус
# читался прямым углом с обточенной вершиной. PULL — насколько кривая
# отпущена к вершине: 0.55 даёт ровно дугу, больше — изгиб мягче дуги.
BEND = 120
BEND_FRAC = 0.46
BEND_PULL = 0.82
# Расстояние между осями соседних ниток: жгут читается парой, а не двумя
# отдельными шлангами, только пока они идут вплотную.
PAIR = 28
# В проходе у стены вентиляторов нитки идут внахлёст: меньше своего диаметра,
# то есть одна лежит на другой. На фотографии живой машины там именно так —
# места ровно на один шланг, и второй кладут поверх, а не рядом.
LAP = 11
TUBE_EDGE = 'rgba(147,161,161,0.26)'

# Коридор, которым магистрали уходят назад. Между процессорами и служебной
# зоной остаётся полоса, и это единственное место, где труба проходит, не
# наступая ни на память, ни на сокеты.
X_TRUNK_HI = 800           # вертикаль подачи
X_TRUNK_LO = 824           # вертикаль обратки, рядом со своей соседкой
# Вывод контура. Стоит он на сплошном перфорированном листе за окнами
# райзеров, а не в проёме слота: планка слота уезжает вместе с картой, а контур
# разъединяют, не трогая расширения. Напротив промежутка между райзерами —
# единственное место стенки, где за ним не стоит ничего своего.
#
# Разведены гнёзда на диаметр разъёма: сойдись ближе, и две накидные гайки не
# затянуть порознь.
Y_OUT_MID = (RISER[0][0] + RISER[0][1] + RISER[1][0]) / 2
Y_OUT_HI = Y_OUT_MID - 13
Y_OUT_LO = Y_OUT_MID + 13
# Гнёзда мельче, чем стояли в проёме слота: полоса между окнами узкая, и пара
# прежнего размера в неё не вставала. Меньше этого их не сделать — под накидную
# гайку нужен хват.
JACK_R = 11
# Шланг заходит под пластину и обрывается под ней: пластина рисуется поверх и
# прикрывает стык, как козырёк на живой стенке.
X_OUT = sum(X_WALL_FIELD) / 2

# Перемычка обходит средний банк слева. Вертикаль стоит между рассыпухой,
# которая кончается на 482, и защёлками памяти: сами гнёзда начинаются на 504,
# но защёлка откинута наружу и занимает полосу до 495. Шланг проходит левее её,
# а не левее гнезда, иначе он ложится ровно на замок.
X_BRIDGE = 481


def corners(points, r=BEND, frac=BEND_FRAC):
    """Углы ломаной, подготовленные к скруглению: (вход, вершина, выход, радиус).

    Одно место, где решается форма колена. По этим же углам сборка рисует путь,
    а `tools/dlc_check.py` считает, где шланг на самом деле лежит: пока форма
    жила только в строке пути, проверять было нечего — проверка меряла ломаную,
    а глаз видел кривую, и расходились они как раз на поворотах.

    Радиус берётся долей соседнего отрезка, а не постоянным числом. Постоянный
    давал ровно ту картинку, за которую схему и ругали: длинная прямая, резкий
    четвертькруг, снова прямая — прямой угол, только с обточенной вершиной.
    Доля растягивает поворот на весь отрезок, и колено читается как прогиб.
    """
    def unit(ax, ay, bx, by):
        dx, dy = bx - ax, by - ay
        length = (dx * dx + dy * dy) ** 0.5 or 1
        return dx / length, dy / length, length

    out = []
    for i in range(1, len(points) - 1):
        (x0, y0), (x1, y1), (x2, y2) = points[i - 1], points[i], points[i + 1]
        ux1, uy1, len1 = unit(x1, y1, x0, y0)
        ux2, uy2, len2 = unit(x1, y1, x2, y2)
        rr = min(r, len1 * frac, len2 * frac)
        out.append(((x1 + ux1 * rr, y1 + uy1 * rr), (x1, y1),
                    (x1 + ux2 * rr, y1 + uy2 * rr), rr))
    return out


def bent(points, r=BEND):
    """Путь по ломаной с плавными коленами.

    Колено ведётся кубической кривой, а не дугой. Дуга меняет кривизну скачком:
    на прямой её нет, в начале дуги она сразу своя — и поворот читается углом,
    даже когда он скруглён. У кривой с касательными вдоль отрезков кривизна
    нарастает от нуля, и шланг выглядит прогнутым, а не сломанным.

    Коэффициент чуть больше того, которым кривой приближают окружность: на
    точном значении получается та же дуга, а нужен изгиб мягче неё.
    """
    d = [f'M{points[0][0]:.0f} {points[0][1]:.0f}']
    for (ax, ay), (vx, vy), (bx, by), _rr in corners(points, r):
        c1x, c1y = ax + (vx - ax) * BEND_PULL, ay + (vy - ay) * BEND_PULL
        c2x, c2y = bx + (vx - bx) * BEND_PULL, by + (vy - by) * BEND_PULL
        d.append(f'L{ax:.0f} {ay:.0f} C{c1x:.0f} {c1y:.0f} {c2x:.0f} {c2y:.0f} '
                 f'{bx:.0f} {by:.0f}')
    d.append(f'L{points[-1][0]:.0f} {points[-1][1]:.0f}')
    return ' '.join(d)


def traced(points, r=BEND, steps=10):
    """Та же трасса плотной ломаной: где шланг лежит после скругления.

    Нужна проверке. По исходным точкам колено срезается вслепую — кривая уходит
    внутрь угла и может лечь на то, что ломаная аккуратно обходила.
    """
    out = [points[0]]
    for (ax, ay), (vx, vy), (bx, by), _rr in corners(points, r):
        c1x, c1y = ax + (vx - ax) * BEND_PULL, ay + (vy - ay) * BEND_PULL
        c2x, c2y = bx + (vx - bx) * BEND_PULL, by + (vy - by) * BEND_PULL
        out.append((ax, ay))
        for i in range(1, steps + 1):
            t = i / steps
            m = 1 - t
            out.append((m ** 3 * ax + 3 * m * m * t * c1x + 3 * m * t * t * c2x + t ** 3 * bx,
                        m ** 3 * ay + 3 * m * m * t * c1y + 3 * m * t * t * c2y + t ** 3 * by))
    out.append(points[-1])
    return out


def tube(d, w=None):
    """Один шланг: тело, кромка и блик по верхней образующей.

    Три пути на одну трубу, а не один с толстой обводкой: у шланга видно
    именно кромку — тёмное тело, светлая граница, — и нарисовать это одной
    линией нечем.
    """
    w = w or TUBE
    common = 'fill="none" stroke-linecap="round" stroke-linejoin="round"'
    return (f'<path d="{d}" {common} stroke="{TUBE_EDGE}" stroke-width="{w + 2}"/>'
            f'<path d="{d}" {common} stroke="{TUBE_COLOR}" stroke-width="{w}"/>'
            f'<path d="{d}" {common} stroke="{TUBE_LIT}" stroke-width="{w * 0.22:.1f}" '
            f'transform="translate(0,-{w * 0.22:.1f})"/>')


def ferrule(cx, cy, deg=0):
    """Обжимная муфта: ею шланг посажен на штуцер.

    Она короткая и чуть шире шланга — на живой машине это единственное место,
    где рукав перестаёт быть гладким, и по ней глаз находит стык.

    Угол берётся от самого шланга, а не от осей: на плите он уходит наискось, и
    муфта, поставленная по оси, читалась квадратом, лежащим рядом с трубой, а
    не надетым на неё.
    """
    w, h = 26, TUBE + 5
    return (f'<rect x="{cx - w / 2:.1f}" y="{cy - h / 2:.1f}" width="{w}" height="{h}" rx="2.5" '
            f'fill="#2f2820" stroke="rgba(147,161,161,0.34)" stroke-width="0.8" '
            f'transform="rotate({deg:.0f} {cx:.1f} {cy:.1f})"/>')


def along(frm, to, dist):
    """Точка на отрезке в `dist` от начала, и угол этого отрезка в градусах."""
    dx, dy = to[0] - frm[0], to[1] - frm[1]
    length = math.hypot(dx, dy) or 1
    return (frm[0] + dx / length * dist, frm[1] + dy / length * dist,
            math.degrees(math.atan2(dy, dx)))


def clip(cx, cy, vertical=False):
    """Клипса: скоба, которой шланг прижат к плате.

    Без них труба висит над платой сама по себе. На живой машине их ставят
    через ладонь — иначе шланг уходит в вентилятор.
    """
    w, h = (TUBE + 9, 7) if not vertical else (7, TUBE + 9)
    return (f'<rect x="{cx - w / 2:.1f}" y="{cy - h / 2:.1f}" width="{w}" height="{h}" rx="2" '
            f'fill="#131c21" stroke="rgba(147,161,161,0.34)" stroke-width="0.8"/>')


def hubs():
    """Штуцеры обеих плит: ближний к фронту и дальний, на середине высоты.

    Числа те же, из которых `cpu` рисует фланцы. Держать их здесь вторым
    списком нельзя — разъедутся, — поэтому они считаются из тех же констант.
    """
    mid0, mid1 = Y_CPU0 + SOCKET_H / 2, Y_CPU1 + SOCKET_H / 2
    near, far = HUB_AT
    return {
        'a0': (X_SOCK + SOCKET_W * near, mid0), 'b0': (X_SOCK + SOCKET_W * far, mid0),
        'a1': (X_SOCK + SOCKET_W * near, mid1), 'b1': (X_SOCK + SOCKET_W * far, mid1),
    }


def tap(name, i=0):
    """Конец патрубка штуцера: точка, в которой шланг на него надет.

    Трассы держатся за неё, а не за середину фланца. Иначе шланг рисуется
    воткнутым в диск, и обжимная муфта повисает поперёк него.
    """
    hx, hy = hubs()[name]
    a = radians(TAPS[name][i] - 90)
    return (hx + TAP_LEN * cos(a), hy + TAP_LEN * sin(a))


def uturn(cx, cy, r, start_deg, end_deg, steps=6):
    """Разворот шланга дугой: точки по окружности вместо колена.

    Ломаная с одним углом даёт залом: развернуть рукав на сто восемьдесят
    градусов одним коленом нельзя, его ведут дугой своего радиуса. Шесть точек
    на полукруг — колена по тридцать градусов, то есть развёрнутые углы в сто
    пятьдесят, а не острые.
    """
    span = end_deg - start_deg
    return [(cx + r * cos(radians(start_deg + span * i / steps)),
             cy + r * sin(radians(start_deg + span * i / steps)))
            for i in range(steps + 1)]


def routes():
    """Трасса контура ломаными: имя → точки.

    Это единственное место, где сказано, где идёт шланг. Рисует по ним
    `render`, проверяет `tools/dlc_check.py`.

    Устройство. Контур собран параллельно, на тройниках ближней плиты: наружная
    подача приходит в её штуцер, там же в него входит шланг от дальней плиты, и
    так же устроен второй штуцер на обратке. Поэтому у ближней плиты четыре
    шланга, у дальней два, и оба её шланга уходят в одну сторону — в проход у
    стены вентиляторов, где идут внахлёст. Ровно это видно на фотографии живой
    машины: считать надо шланги в кадре, а не путь жидкости.

    Разворотов нет ни одного. Они появились, когда правила требовали входить в
    штуцер со стороны фронта: шланг честно обходил зону и возвращался, правила
    сходились, а машина выглядела намотанной. Штуцер принимает шланг с той
    стороны, с которой тот идёт, и это нормально — на фотографии так же.
    """
    h = hubs()
    mid0, mid1 = h['a0'][1], h['a1'][1]
    # Обе нитки связки идут левее памяти: правее для них полосы нет, там банки.
    # Внешняя — подача, внутренняя — обратка. Порядок не косметика: поменяй их
    # местами, и у нижней плиты шланги перейдут один через другой.
    lane_out = X_BRIDGE - LAP
    lane_in = X_BRIDGE
    right = X_SOCK + SOCKET_W + 190

    # Наружная подача: от гнезда IN налево, по верхней плите поверх дальнего
    # штуцера, в тройник ближнего. Прогон идёт по самой плите, а не над банком
    # памяти: банк кончается на 178, и шланг лёг бы на плашки.
    feed = [(X_OUT, Y_OUT_HI), (right + 90, Y_OUT_HI), (right, mid0 - 10 - PAIR),
            (h['a0'][0] + 60, mid0 - 10 - PAIR), tap('a0', 0)]

    # Второй выход того же тройника: вниз внешней ниткой связки и под нижней
    # плитой к дальнему её штуцеру. Внешняя нитка идёт до дальнего, внутренняя
    # до ближнего — накрест: так шланг ложится на плиту наискось, как на
    # фотографии, а не подходит к ней в упор.
    #
    # Сворачивает в проход выше соседа и сходит с него ниже — иначе две
    # транзитные нитки перекрещиваются. Порядок в проходе тут не спасает: у
    # нижней плиты он обратный, и разводит их только высота, на которой каждая
    # входит в проход.
    down = [tap('a0', 1), (h['a0'][0] - 70, mid0 + 16), (lane_out, mid0 + 46),
            (lane_out, mid1 + 42), (h['b1'][0] - 100, mid1 + 72), tap('b1', 0)]

    # От ближнего штуцера нижней плиты: влево в проход, внутренней ниткой вверх
    # мимо памяти и во второй тройник верхней.
    up = [tap('a1', 0), (h['a1'][0] - 80, mid1 - 5), (lane_in, mid1 - 45),
          (lane_in, mid0 + 91), (h['b0'][0] - 100, mid0 + 41), tap('b0', 1)]

    # Наружная обратка: из того же тройника направо, к гнезду OUT. Идёт рядом с
    # подачей, но своей полосой: на общем уровне они легли бы одна на другую и
    # читались как один шланг. Гнездо своё — стрелки на пластине смотрят туда же.
    ret = [tap('b0', 0), (h['b0'][0] + 90, mid0 - 10), (right, mid0 - 10),
           (right + 90, Y_OUT_LO), (X_OUT, Y_OUT_LO)]

    return {'feed': feed, 'down': down, 'up': up, 'ret': ret}


def render(cv):
    """Один контур: всё уходит к фронту и обходит память слева.

    Штуцеры обеих плит смотрят в одну сторону — к вентиляторам, — и шланг
    выходит из них туда же. Дальше он разворачивается широкой петлёй и ложится
    вдоль плиты: на фотографии магистраль лежит на самой плите, а не проходит
    стороной. Над памятью и справа от неё не идёт ничего: единственный проход,
    которым шланг обходит банки, — слева, у стены вентиляторов.

    Углы у трассы развёрнутые, а не прямые. Прямой угол на рукаве такого
    диаметра — это залом; его ведут наискось, длинной дугой, и на снимке видно
    именно косые колена.
    """
    mid0, mid1 = Y_CPU0 + SOCKET_H / 2, Y_CPU1 + SOCKET_H / 2
    hub_a0, hub_a1 = hubs()['a0'], hubs()['a1']
    off = TUBE / 2 + 8

    # Четыре шланга: два наружных у ближней плиты и два, которыми к её
    # тройникам подключена дальняя. Порядок отрисовки — порядок наложения: в
    # проходе нитки идут внахлёст, и та, что рисуется позже, лежит поверх.
    line = routes()
    hoses = ''.join(tube(bent(line[k])) for k in ('feed', 'ret', 'down', 'up'))

    # Скобы плиты. Прежние уходили дугой за её габарит — на живой плите они
    # целиком лежат на ней, и форма у них другая.
    #
    # Длинная идёт от ближнего штуцера вдоль плиты почти до дальнего, там
    # разворачивается на сто восемьдесят — той же дужкой, что ручка блока
    # питания, — и возвращается по второй ветви к угловому болту.
    def retainer(hub, far):
        near_y = hub[1] + 24        # ветвь туда
        back_y = hub[1] + 50        # ветвь обратно
        turn_x = far[0] + 20
        return (bent([(hub[0] + 6, hub[1] + 14), (turn_x - 46, near_y)]
                     + uturn(turn_x, (near_y + back_y) / 2, (back_y - near_y) / 2, -90, 90)
                     + [(turn_x - 46, back_y), (X_SOCK + 24, back_y)], r=18))

    # Малая скоба — над ближним штуцером, коротким зигзагом с маленькой дужкой.
    # Дужка именно маленькая: большая читалась второй магистралью, а это всего
    # лишь пружинный зацеп, каким прижата кромка.
    def latch(hub):
        return bent([(hub[0] - 2, hub[1] - 22), (hub[0] - 14, hub[1] - 28)]
                    + uturn(hub[0] - 16, hub[1] - 37, 9, 100, 260)
                    + [(hub[0] - 2, hub[1] - 44)], r=6)

    braces = ''.join((
        tube(retainer(hubs()['a1'], hubs()['b1']), w=7),
        tube(retainer(hub_a0, hubs()['b0']), w=7),
        tube(latch(hubs()['a1']), w=5), tube(latch(hub_a0), w=5),
    ))

    # Датчик протечки: самый тонкий из всего, что тут проложено, и лежит он под
    # магистралью, а не в обход неё.
    sx, sy = X_SOCK - 54, Y_CPU1 + SOCKET_H - 30
    leak = bent([(hub_a1[0] - 30, mid1 + 30), (hub_a1[0] - 84, mid1 + 54), (sx + 30, sy + 16)],
                r=20)
    sensor = (f'<rect x="{sx}" y="{sy + 4}" width="30" height="24" rx="2" '
              f'fill="#c9c3ae" fill-opacity="0.22" stroke="rgba(223,232,234,0.26)"/>'
              f'<rect x="{sx + 6}" y="{sy + 10}" width="18" height="12" rx="1.5" '
              f'fill="#1a1611" stroke="rgba(147,161,161,0.34)"/>')

    # Муфта садится на конец патрубка и разворачивается вместе с ним: у тройника
    # их две, и стоящая по оси читалась бы квадратом, лежащим рядом со шлангом.
    ferrules = ''.join(
        ferrule(*tap(name, i), deg=TAPS[name][i] - 90)
        for name in ('a0', 'b0', 'a1', 'b1') for i in range(len(TAPS[name])))
    # Муфты у стенки стоят перед пластиной, а не под ней: под ней их не видно.
    ferrules += (ferrule(X_WALL_FIELD[0] - 22, Y_OUT_HI)
                 + ferrule(X_WALL_FIELD[0] - 22, Y_OUT_LO))

    clips = ''.join((
        clip(X_BRIDGE, (mid0 + mid1) / 2 - 80, vertical=True),
        clip(X_BRIDGE, (mid0 + mid1) / 2 + 80, vertical=True),
        clip(X_SOCK + SOCKET_W + 30, mid1 + off),
        clip(X_SOCK + SOCKET_W + 30, mid0 - off),
    ))

    # Бронь по коридорам: проход у кромки памяти и два прогона вдоль плит.
    cv.busy(X_BRIDGE - TUBE / 2, mid0, TUBE, mid1 - mid0, pad=0)
    cv.busy(hub_a0[0] - 100, mid0 - off - TUBE / 2, X_TRUNK_HI - hub_a0[0] + 100, TUBE, pad=0)
    cv.busy(hub_a1[0] - 100, mid1 + off - TUBE / 2, X_TRUNK_HI - hub_a1[0] + 100, TUBE, pad=0)
    # Подход к стенке в две брони, а не в одну на весь угол: магистрали идут
    # вдоль плиты, а вниз, к своим гнёздам, сворачивают только у самой стенки.
    # Броня на весь угол закрывала бы половину служебной зоны, где трубы не
    # проходят вовсе, и рассыпуху из неё пришлось бы выселять зря.
    cv.busy(X_TRUNK_LO, mid0 - off - TUBE, X_TRUNK_LO + 176 - X_TRUNK_LO,
            TUBE * 3, pad=0)
    cv.busy(X_TRUNK_LO + 176, mid0 - off - TUBE, X_OUT - X_TRUNK_LO - 176,
            Y_OUT_LO + TUBE - (mid0 - off - TUBE), pad=0)
    cv.busy(sx, sy + 4, 30, 24, pad=0)

    cv.add('<g class="dlc-loop decor">'
           + sensor
           + tube(leak, w=5)
           + braces
           + hoses
           + ferrules + clips
           + mono(sx + 36, sy + 20, "LEAK", 5, anchor="start", op=0.4)
           + '</g>')
    # Пластина кладётся после шлангов и накрывает их концы: на живой машине
    # шланг уходит под неё, а не лежит поверх стенки.
    cv.add(f'<g class="dlc-panel decor">{outlet()}</g>')


def outlet():
    """Вывод контура в задней стенке: пластина и два быстроразъёма.

    Пластина накладная: она лежит на перфорированном листе за окнами райзеров,
    и шланги уходят под неё — стык шланга с гнездом на живой машине закрыт
    именно так. Слот при этом остаётся слотом: контур ничего у расширения не
    отбирает, потому что врезан не в планку, а в саму стенку.

    Оба разъёма одинаковые: у сухоразъёмного соединения половинки не
    различаются ничем, кроме того, куда они врезаны, и подписаны они поэтому не
    цветом, а словом и стрелкой.

    Голубой поясок — тот же код, что у райзера и памяти: контур разъединяют на
    обесточенной машине, а не на ходу.
    """
    x0, x1 = X_WALL_FIELD
    pad = JACK_R + 7
    out = [f'<rect x="{x0}" y="{Y_OUT_HI - pad}" width="{x1 - x0}" '
           f'height="{Y_OUT_LO - Y_OUT_HI + pad * 2}" rx="3" fill="{STEEL}" '
           f'stroke="rgba(147,161,161,0.30)"/>']
    for cy, label, into in ((Y_OUT_HI, "IN", True), (Y_OUT_LO, "OUT", False)):
        cx = (x0 + x1) / 2
        out.append(
            # Гнездо: корпус, накидная гайка, поясок и зев.
            f'<circle cx="{cx}" cy="{cy}" r="{JACK_R}" fill="#131c21" '
            f'stroke="rgba(147,161,161,0.38)" stroke-width="1.2"/>'
            f'<circle cx="{cx}" cy="{cy}" r="{JACK_R - 3.4}" fill="none" stroke="{COLD}" '
            f'stroke-opacity="0.55" stroke-width="1.8"/>'
            f'<circle cx="{cx}" cy="{cy}" r="{JACK_R - 6}" fill="#070d10" '
            f'stroke="rgba(147,161,161,0.30)"/>'
            # Стрелка: внутрь машины у подачи, наружу у обратки.
            + (f'<path d="M{cx - JACK_R - 15} {cy} h11 m-4 -4 l4 4 -4 4" fill="none" '
               f'stroke="rgba(147,161,161,0.55)" stroke-width="1.4" stroke-linecap="round"/>'
               if into else
               f'<path d="M{cx + JACK_R + 4} {cy} h11 m-4 -4 l4 4 -4 4" fill="none" '
               f'stroke="rgba(147,161,161,0.55)" stroke-width="1.4" stroke-linecap="round"/>')
            + mono(cx + (JACK_R + 5 if into else -JACK_R - 5), cy + 3, label, 5.4,
                   anchor="middle", op=0.44))
    return ''.join(out)
