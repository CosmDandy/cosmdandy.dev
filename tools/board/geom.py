"""Координаты: единственное место, где написано, что где лежит.

Это общий стол — файл, который нельзя править параллельно. Всё остальное
можно: блок берёт отсюда свои границы и рисует внутри них, не заглядывая к
соседям. Пока координата узла живёт в коде самого узла, соседи связаны
через неё, и «править отдельно» не работает.

Композиция повёрнута на 90°: фронт слева, глубина вправо — экран широкий, а
сервер длинный. Поэтому X_* — это глубина от фронта, Y_* — ширина шасси.
"""

W, H = 1314, 863

# ── глубина: от фронта к задней стенке ───────────────────────────────────
X_FRONT  = 6      # фронт: блок управления сверху, отсеки дисков под ним
X_BP     = 166    # backplane — вплотную к корзине, за решёткой отсеков
X_FAN    = 198    # стенка вентиляторов
FAN_N    = 8      # модулей в стенке; шаг и высота — ниже, они нужны и разводке
FAN_W    = 132    # стенка ужимается правым краем: левый стоит на месте, а
                  # освободившаяся глубина уходит плате
X_PCB    = 346    # плата подступает к стенке вплотную: между ними ровно
                  # столько, чтобы читались жгуты питания вентиляторов
X_CORE   = 504    # слоты памяти
X_SVC    = 842    # служебная зона: батарея, microSD, M.2
X_REAR   = 1004   # отсеки БП
X_IO     = 1214   # задняя панель

# Шаг стенки вентиляторов знает не только она: к колодке каждого модуля
# идёт своя шина питания, и разводка обязана попадать в ту же точку.
FAN_STEP = (H - 52) / FAN_N
FAN_H    = FAN_STEP - 8


def fan_foot_y(i):
    """Ордината колодки i-го вентилятора на плате — против середины модуля."""
    return 26 + i * FAN_STEP + FAN_H / 2 - 8


FRONT_W  = 156    # каддики плюс решётка той же ширины
# Блок управления: корзина начинается под ним и потому подвинулась вниз.
# Прежних 150 хватало на ряд кнопок поперёк, а панель диагностики встала
# вдоль левой кромки — ей нужна вся высота блока, и кнопкам осталась
# правая половина.
Y_PANEL  = 196

# ── ширина: 8 DIMM | CPU0 | 8 DIMM | CPU1 | 8 DIMM ───────────────────────
# Двадцать четыре слота, по двенадцать на процессор. Тридцать два не влезали:
# 544 единицы памяти плюс два сокета по 150 — это вся ширина шасси без
# остатка, и банки наезжали на сокеты. Теперь между каждой парой соседей
# ровно 28 — туда и встают шелкография банка и метка VRM.
PITCH = 17
SLOT_H = 15
Y_BANK_L, Y_CPU0, Y_BANK_C, Y_CPU1, Y_BANK_R = 34, 194, 368, 528, 702
BANK_N = 8        # планок в банке; ширина банка = BANK_N * PITCH
DIMM_SOCK_W = 292  # длина разъёма памяти по глубине платы
SOCKET_W, SOCKET_H = 202, 150   # LGA 4677 заметно прямоугольный

Y_PSU_TOP, Y_PSU_BOT = 172, 690
X_PCB_END = 1206

X_TAG = 470       # ярлыки ядра платы — в пустой левой части, друг под другом

# поле платы: по нему раскладывают рассыпуху, разводку и отверстия
PCB_W, PCB_H = X_REAR - 4 - X_PCB, H - 36

# ── места узлов ──────────────────────────────────────────────────────────
# Раньше эти координаты жили внутри блоков, и чтобы узнать, где стоит сокет,
# крышке приходилось импортировать процессоры целиком. Теперь наоборот: и
# сокет, и крышка спрашивают одно и то же место здесь.
X_SOCK = X_CORE + 40                  # процессорные крышки
X_VRM  = X_CORE - 20                  # дроссели питания ядра, вплотную к сокету

# Крупные корпуса. Раньше они садились в первое свободное место обхода и
# сбивались в кучу у левой кромки; теперь место каждого выбрано руками и
# объявлено здесь, потому что на него опираются три слоя разом: разводка
# тянет к чипу шину, обвязка садится кольцом вокруг, медь его обтекает.
# Полоса между колодками вентиляторов и банками памяти — единственное, что
# на плате не занято, поэтому корпуса идут вдоль неё, но с разбегом по краю.
# Полоса у левой кромки узкая, и делят её трое: корпуса, гребёнки шлейфов и
# электролиты питания ядра. Поэтому ординаты чередуются, а сетевой контроллер
# и TPM уехали в проём между райзерами — контроллеру там и место, у самых
# гнёзд задней панели.
CHIPS = (
    ('AST2600',  'U79',  436,  46, 46, 46),   # BMC
    ('PCH C741', 'U31',  438, 120, 44, 44),   # чипсет
    ('PCIe SW',  'U44',  436, 380, 42, 42),   # коммутатор линий на райзеры
    ('CPLD',     'U12',  442, 700, 34, 34),   # логика последовательности питания
    ('X710',     'U21', 1016, 382, 36, 36),   # сетевой контроллер
    ('TPM 2.0',  'U9',  1080, 384, 32, 26),
)

BAY_TOP, BAY_N, GROUPS = Y_PANEL + 8, 8, 4   # корзина дисков
GROUP_GAP = 10
# Пара каддиков по глубине занимает столько, сколько раньше занимал один:
# 2,5″ узкий, и корзина из восьми таких — это тонкий пакет у самого фронта.
# Всё, что осталось от глубины фронта, уходит под вентиляционную решётку —
# через неё вентиляторы и тянут воздух сквозь диски.
BAY_DEPTH = 78
BAY_W = BAY_DEPTH / 2
GROUP_H = (H - 12 - BAY_TOP - GROUP_GAP * (GROUPS - 1)) / GROUPS
CAP = 46

LID_BTN = (X_SVC + 26, 508, 86)       # кнопка крышки: x, y, сторона квадрата
