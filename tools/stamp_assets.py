"""Версия в ссылках на статику: кэшируется навсегда, обновляется само.

Задача противоречивая только на вид. Хочется, чтобы браузер не переспрашивал
стили и скрипт вовсе — но чтобы правка доходила до того, кто уже открывал сайт.
Одним заголовком это не решается: `immutable` на постоянном имени означает
«никогда не обновится», а без него каждый заход стоит четырёх условных запросов,
и два из них — до первого кадра.

Решение — сделать имя зависимым от содержимого. Ссылка получает `?v=<хэш>`, а
хэш считается от самого файла. Поменялся файл — поменялась ссылка, и для
браузера это другой адрес, который он ещё не видел. Не поменялся — адрес тот
же, и файл берётся из кэша не спрашивая.

Почему запрос, а не хэш в имени файла. Хэш в имени честнее и потому считается
образцом, но он требует переименовывать файлы при сборке и держать в порядке
всё, что на них ссылается, — включая `_headers`, манифест и лишний слой
неочевидности в репозитории, где статика лежит под постоянными именами
нарочно. Запрос даёт тот же ключ кэша при том же содержимом и не трогает
файловую систему.

Просроченный кэш при этом невозможен по устройству: страница переспрашивается
всегда, а в ней всегда лежит текущий хэш. Голый адрес без `?v=` тоже безопасен —
это отдельный ключ кэша, и отравить им версионированный нельзя.

Работает поверх собранных страниц и повторяется без вреда: старый `?v=` в
ссылке заменяется новым. Корень можно указать аргументом — в конвейере это
_site, уже минифицированный: хэш обязан считаться от того, что реально уедет
по проводу, иначе правка одного лишь минификатора не сдвинет ссылку и до
вернувшегося гостя не дойдёт никогда — заголовок обещает год.

    python3 tools/stamp_assets.py [корень]
"""

import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

# Что версионируем и на каких страницах. Пути относительные — такими они и
# стоят в разметке, и такими же ищутся на диске рядом со страницей.
ASSETS = ("style.css", "server.css", "server.js")

PAGES = ("index.html", "404.html", "tg/index.html")


def digest(path):
    """Восемь знаков хэша содержимого — этого хватает и на глаз читается."""
    return hashlib.sha256(path.read_bytes()).hexdigest()[:8]


def main(argv):
    root = Path(argv[0]) if argv else HERE
    changed = []
    for name in PAGES:
        page = root / name
        if not page.exists():
            continue
        html = page.read_text(encoding="utf-8")
        before = html
        for asset in ASSETS:
            src = (page.parent / asset)
            if not src.exists():
                continue
            ver = digest(src)
            # Ссылка ищется вместе с уже проставленной версией, если она есть,
            # иначе повторный прогон дописал бы второй `?v=` к первому.
            pat = re.compile(r'(["\'])' + re.escape(asset) + r'(?:\?v=[0-9a-f]+)?\1')
            html = pat.sub(lambda m, a=asset, v=ver: f'{m.group(1)}{a}?v={v}{m.group(1)}', html)
        if html != before:
            page.write_text(html, encoding="utf-8")
            changed.append(name)
    marks = []
    for asset in ASSETS:
        src = root / asset
        if src.exists():
            marks.append(f"{asset}={digest(src)}")
    print(f"версии статики: {' '.join(marks)}"
          f" · переписано страниц: {len(changed)}")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
