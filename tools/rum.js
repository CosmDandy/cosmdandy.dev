// Сколько страница стоила настоящему гостю.
//
// Лабораторная мерка (tools/perf-matrix.mjs) меряет контейнер разработки с
// эмуляцией телефона: она отвечает на вопрос «стало ли хуже, чем вчера», и
// отвечает точно. Чего она не знает — какой на самом деле телефон, какая
// сеть и сколько до ближайшего края сети. Это знает только сам гость.
//
// Почему свой сборщик, а не библиотека. Готовые считают пять метрик Web
// Vitals, из которых на этой странице две не существуют: LCP не наступает
// вовсе — его кандидатами Chrome считает картинки и текстовые блоки, а вся
// схема это inline <svg>; на узком экране не наступает и FCP. Библиотека
// молчала бы там, где интереснее всего, и весила бы три килобайта ради этого
// молчания.
//
// Отправляется всё одним пакетом на выгрузке страницы: раньше отправлять
// нечего — метрики дозревают по ходу, — а позже уже некому.
(function () {
    // Отправляем только с продакшена: на localhost и превью-стендах мерки
    // врут (сеть своя, процессор свой) и только засоряют журнал.
    //
    // Продакшен опознаётся отсутствием отметки о сборке — тем же признаком,
    // по которому в проекте показывается панель слоёв. Пайплайн стирает
    // содержимое отметки только на боевом стенде. Домен здесь не годится:
    // записанный числом, он молча перестал бы работать при переезде, а
    // отметка ставится тем же, кто разворачивает.
    // Тег обязан быть и обязан быть пустым. «Нет тега» — это не продакшен,
    // а страница, которую забыли проштамповать: мягкая проверка пускала бы
    // мерки с localhost и с каждого превью-стенда.
    var stamp = document.querySelector('meta[name="build"]');
    if (!stamp || stamp.content) return;
    if (!navigator.sendBeacon) return;

    var m = {};
    var sent = false;
    var nav = performance.getEntriesByType('navigation')[0];

    // Сдвиги макета копятся до самого конца: элемент, приехавший на третьей
    // секунде, сдвигает всё под собой так же, как приехавший на первой.
    var cls = 0;
    try {
        new PerformanceObserver(function (list) {
            list.getEntries().forEach(function (e) {
                // Сдвиг сразу после нажатия — это ответ на действие, а не
                // рывок: гость его ожидал.
                if (!e.hadRecentInput) cls += e.value;
            });
        }).observe({ type: 'layout-shift', buffered: true });
    } catch (e) { /* нет поддержки — метрики просто не будет */ }

    // Отзывчивость: самое долгое ожидание ответа на действие за весь визит.
    // Это упрощённый INP — настоящий берёт 98-й процентиль, но на визитке
    // взаимодействий единицы, и худшее из них честнее процентиля по трём.
    var inp = 0;
    try {
        new PerformanceObserver(function (list) {
            list.getEntries().forEach(function (e) {
                if (e.duration > inp) inp = e.duration;
            });
        }).observe({ type: 'event', durationThreshold: 16, buffered: true });
    } catch (e) { /* то же самое */ }

    function send() {
        // Один визит — одна мерка. Отправку зовут два события, и `once` на
        // каждом снимает только свой обработчик: в журнал уезжало по две
        // одинаковые записи на визит, и лента, по которой сравнивают «до и
        // после выкатки», была вдвое гуще правды.
        if (sent || !nav) return;
        sent = true;
        m.ttfb = nav.responseStart;
        m.dcl = nav.domContentLoadedEventEnd;
        m.load = nav.loadEventEnd;
        var paint = performance.getEntriesByName('first-contentful-paint')[0];
        if (paint) m.fcp = paint.startTime;
        var lcp = performance.getEntriesByType('largest-contentful-paint').pop();
        if (lcp) m.lcp = lcp.startTime;
        if (cls) m.cls = cls;
        if (inp) m.inp = inp;

        var conn = navigator.connection || {};
        navigator.sendBeacon('/rum', JSON.stringify({
            m: m,
            // Вид решает ширина, и он же решает, за что гость заплатил: на
            // узком экране схемы нет, а её вес приезжает.
            v: document.body.classList.contains('view-rig') ? 'rig' : 'card',
            w: innerWidth,
            n: conn.effectiveType || null,
            // Тёплый заход: по проводу приехало меньше, чем страница весит.
            // Нулём это не опознать — с тех пор как воркер ставит метку
            // версии, повторный заход отвечает 304, а у него transferSize
            // равен весу заголовков, а не нулю.
            c: nav.transferSize > 0 && nav.transferSize < nav.decodedBodySize
        }));
    }

    // pagehide, а не unload: с ним страница остаётся пригодной для обратного
    // хода в истории, и на мобильных он единственный, который вообще
    // случается — вкладку там не закрывают, её убивают.
    addEventListener('pagehide', send);
    // Скрытие вкладки — тот же конец визита с точки зрения мерки: гость ушёл,
    // и вернуться может через час. Что сработает первым, неизвестно, и от
    // повтора защищает флаг внутри send, а не `once` на каждом слушателе.
    addEventListener('visibilitychange', function () {
        if (document.visibilityState === 'hidden') send();
    });
})();
